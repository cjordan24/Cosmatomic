/** Phase 14 browser verification (Advanced Foundations). Screenshots → screenshots/phase-14/. Offline/deterministic. */
import { test, expect, type Page } from '@playwright/test';
import { mkdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '../../screenshots/phase-14');
mkdirSync(OUT, { recursive: true });
const INDEX = join(OUT, 'captures.json');
const log: Record<string, string> = existsSync(INDEX) ? JSON.parse(readFileSync(INDEX, 'utf8')) : {};
async function shot(page: Page, name: string, description: string) {
  await page.waitForTimeout(700);
  await page.screenshot({ path: join(OUT, `${name}.png`) });
  log[`${name}.png`] = description;
  writeFileSync(INDEX, JSON.stringify(log, null, 2));
  const md = ['# Phase 14 screenshots', '', 'Generated by `tests/e2e/phase14.spec.ts` from the running application (Playwright, Chromium + SwiftShader). Not edited.', '',
    ...Object.entries(log).sort(([a], [b]) => a.localeCompare(b)).map(([f, d]) => `- **${f}** — ${d}`), ''].join('\n');
  writeFileSync(join(OUT, 'INDEX.md'), md);
}
const errors: string[] = [];
test.beforeEach(({ page }) => { page.on('pageerror', (e) => errors.push(e.message)); });
test.afterEach(() => { expect(errors, errors.join(' | ')).toEqual([]); });

// ---------------- Gate 14.1 ----------------
test('109 particles: the Standard Model with PDG 2025 values and DOE sentences', async ({ page }) => {
  await page.goto('/#/atomic');
  await page.getByRole('navigation', { name: 'Atomic sections' }).getByRole('button', { name: 'Subatomic ▾' }).click();
  await page.getByRole('menuitem', { name: 'Particles' }).click();
  await expect(page).toHaveURL(/#\/atomic\/particles$/);
  const bar = await page.locator('header.topbar').boundingBox(), acts = await page.locator('.topbar-actions').boundingBox();
  expect(acts!.x + acts!.width).toBeLessThanOrEqual(bar!.x + bar!.width + 1);
  const v = page.getByLabel('Particle values');
  await expect(v).toContainText('0.51099895000 ± 0.00000000015 MeV');
  await expect(page.locator('h1')).toContainText('The particles of the Standard Model');
  await page.waitForTimeout(800);
  await shot(page, '109a-particles', 'Particles (Gate 14.1): quarks, leptons, gauge bosons and the Higgs with the Particle Data Group’s 2025 values (CC BY 4.0), on a log mass scale from the electron to the top quark; DOE Office of Science sentences.');
  await page.getByRole('list', { name: 'Quarks' }).getByRole('listitem').filter({ hasText: /^t$/ }).click();
  await expect(v).toContainText('172.56 ± 0.31 GeV');
  await expect(page.locator('.center-stage')).toContainText('MS‾ masses at the scale μ = 2 GeV');
  await page.getByRole('list', { name: 'Gauge bosons' }).getByRole('listitem').filter({ hasText: 'Z⁰' }).click();
  await expect(v).toContainText('91.1880 ± 0.0020 GeV');
});

// ---------------- Gate 14.2 ----------------
test('110 quantum lab: Schrödinger’s equation solved numerically; box, oscillator, tunnelling', async ({ page }) => {
  await page.goto('/#/atomic/particles');
  await page.getByRole('navigation', { name: 'Atomic sections' }).getByRole('button', { name: 'Subatomic ▾' }).click();
  await page.getByRole('menuitem', { name: 'Quantum lab' }).click();
  await expect(page).toHaveURL(/#\/atomic\/quantum$/);
  const E = page.getByLabel('Energy levels');
  await expect(E).toContainText('0.37603');        // numerical E₁, 1 nm box
  await expect(E).toContainText('exact 0.37603');
  await expect(page.locator('.center-stage')).toContainText('5.5 × 10⁻⁷');   // Mott finding
  await shot(page, '110a-box', 'Quantum lab (Gate 14.2): an electron in a 1 nm box — Schrödinger’s equation solved on a 500-point grid; the first four levels agree with Mott’s n²h²/8ml² (0.37603 eV for n = 1). Finding: Mott’s 1-cm example prints 3·2 × 10⁻⁷ V, his formula gives 5.5 × 10⁻⁷ V.');
  await page.getByRole('button', { name: 'Spring (oscillator)' }).click();
  await expect(E).toContainText('exact 0.25');
  await expect(E).toContainText('exact 1.75');
  await shot(page, '110b-oscillator', 'The harmonic oscillator with ħω = 0.5 eV: numerical levels 0.24999, 0.74997, … against Schrödinger’s (25′) Eₙ = ((2n + 1)/2)hν₀.');
  await page.getByRole('navigation', { name: 'Quantum sections' }).getByRole('button', { name: 'Tunnelling' }).click();
  await expect(page.getByLabel('Tunnelling values')).toContainText('0.1014');
  await expect(page.locator('.center-stage')).toContainText('slipping through the mountain');
  await shot(page, '110c-tunnel', 'Tunnelling: a 0.5 eV electron through a 1 eV, 0.5 nm barrier passes with T = 0.1014; resonances above the top (Condon & Morse 1929). Finding: their eq. (68.5) is printed with a wrong sign.');
});

// ---------------- Gate 14.3 ----------------
test('111 nuclei: binding energies from NUBASE2020, a liquid-drop fit, the U-238 series and the pp chain', async ({ page }) => {
  await page.goto('/#/atomic/quantum');
  await page.getByRole('navigation', { name: 'Atomic sections' }).getByRole('button', { name: 'Subatomic ▾' }).click();
  await page.getByRole('menuitem', { name: 'Nuclei' }).click();
  await expect(page).toHaveURL(/#\/atomic\/nuclei$/);
  const b = page.getByLabel('Binding values');
  await expect(b).toContainText('492.26 MeV');
  await expect(b).toContainText('8.7904');
  await expect(page.getByRole('table', { name: 'Published coefficients' })).toContainText('15.753');
  await shot(page, '111a-binding', 'Nuclei (Gate 14.3): binding energy per nucleon of every NUBASE2020 nuclide; the liquid-drop formula fitted to 2292 of them (rms 2.86 MeV) beside Green’s, Wapstra’s and Bethe & Bacher’s coefficients as tabulated by Wing (1964).');
  const nav = page.getByRole('navigation', { name: 'Nuclei sections' });
  await nav.getByRole('button', { name: 'Chart of nuclides' }).click();
  await shot(page, '111b-chart', 'The chart of nuclides: every NUBASE2020 ground state with a mass, coloured by half-life.');
  await nav.getByRole('button', { name: 'Decay series' }).click();
  await expect(page.getByRole('list', { name: 'Decay steps' }).getByRole('listitem')).toHaveCount(15);
  await shot(page, '111c-u238', 'The uranium-238 series (USGS) with NUBASE2020 half-lives: 14 decays from U-238 to stable Pb-206.');
  await nav.getByRole('button', { name: 'Fusion in stars' }).click();
  const pp = page.getByLabel('pp chain energies');
  await expect(pp).toContainText('1.442'); await expect(pp).toContainText('5.493'); await expect(pp).toContainText('12.86'); await expect(pp).toContainText('26.73');
  await shot(page, '111d-pp', 'Fusion in the Sun: NASA’s three steps of the pp chain with energies from NUBASE2020 masses — 1.442, 5.493 and 12.86 MeV, 26.73 MeV in all (PDG: “∼ 26 MeV”).');
});
