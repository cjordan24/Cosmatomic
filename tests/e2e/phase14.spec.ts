  await shot(page, '110a-box', 'Quantum lab (Gate 14.2): an electron in a 1 nm box — Schrödinger’s equation solved on a 500-point grid; the first four levels agree with Mott’s n²h²/8ml² (0.37603 eV for n = 1). Finding: Mott’s 1-cm example prints 3·2 × 10⁻⁷ V, his formula gives 5.5 × 10⁻⁷ V.');
