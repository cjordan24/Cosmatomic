/** Phase 12 browser verification (Human Anatomy & Physiology). Screenshots → screenshots/phase-12/. Offline/deterministic. */
import { test, expect, type Page } from '@playwright/test';
import { mkdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '../../screenshots/phase-12');
mkdirSync(OUT, { recursive: true });
const INDEX = join(OUT, 'captures.json');
const log: Record<string, string> = existsSync(INDEX) ? JSON.parse(readFileSync(INDEX, 'utf8')) : {};
async function shot(page: Page, name: string, description: string) {
  await page.waitForTimeout(700);
  await page.screenshot({ path: join(OUT, `${name}.png`) });
  log[`${name}.png`] = description;
  writeFileSync(INDEX, JSON.stringify(log, null, 2));
  const md = ['# Phase 12 screenshots', '', 'Generated by `tests/e2e/phase12.spec.ts` from the running application (Playwright, Chromium + SwiftShader). Not edited.', '',
    ...Object.entries(log).sort(([a], [b]) => a.localeCompare(b)).map(([f, d]) => `- **${f}** — ${d}`), ''].join('\n');
  writeFileSync(join(OUT, 'INDEX.md'), md);
}
const errors: string[] = [];
test.beforeEach(({ page }) => { page.on('pageerror', (e) => errors.push(e.message)); });
test.afterEach(() => { expect(errors, errors.join(' | ')).toEqual([]); });

// ---------------- Gate 12.1 ----------------
test('101 human body: BodyParts3D organs in 3D, selection, isolation, quoted facts and the model’s own sizes', async ({ page }) => {
  await page.goto('/#/biologic');
  await page.getByRole('navigation', { name: 'Biologic sections' }).getByRole('button', { name: 'Body ▾' }).click();
  await page.getByRole('menuitem', { name: 'Human body' }).click();
  await expect(page).toHaveURL(/#\/biologic\/body$/);
  await expect(page.locator('.stage-head h1')).toContainText('The human body');
  const bar = await page.locator('header.topbar').boundingBox(), acts = await page.locator('.topbar-actions').boundingBox();
  expect(acts!.x + acts!.width).toBeLessThanOrEqual(bar!.x + bar!.width + 1);   // the top bar still fits at 1440 px
  await expect(page.getByRole('list', { name: 'Organ list' }).getByRole('listitem')).toHaveCount(11);
  await page.waitForTimeout(4000);   // ~3 MB model
  await shot(page, '101a-body', 'The human body (Gate 12.1): skeleton and ten organs from BodyParts3D 4.0 (DBCLS, CC BY 4.0), decimated in Blender to 140 000 triangles, coloured by organ system; the ten systems as SEER names them.');
  await page.getByRole('list', { name: 'Organ list' }).getByRole('button', { name: 'Right kidney' }).click();
  const m = page.getByLabel('Model measurements');
  await expect(m).toContainText('10.4');
  await expect(m).toContainText('106.1');
  await expect(page.locator('.right-panel')).toContainText('approximately 3 cm thick, 6 cm wide, and 12 cm long');
  await expect(page.locator('.right-panel')).toContainText('about a million filtering units called nephrons');
  await page.getByRole('button', { name: 'Isolate selected' }).click();
  await page.waitForTimeout(1500);
  await shot(page, '101b-kidney-isolated', 'The right kidney isolated: the model measures 10.4 × 5.7 × 4.7 cm and 106 cm³ (full-resolution BodyParts3D data), beside SEER’s “approximately 3 cm thick, 6 cm wide, and 12 cm long” and NIDDK’s million nephrons.');
  await page.getByRole('button', { name: 'Reset' }).click();
  await page.getByRole('list', { name: 'Organ list' }).getByRole('button', { name: 'Right lung (airways and vessels)' }).click();
  await expect(page.locator('.warn-note')).toContainText('not the lung tissue itself');
});
