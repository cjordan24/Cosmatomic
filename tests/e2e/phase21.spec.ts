/** Phase 21 browser verification (Meteorology: Earth weather and storms). Screenshots → screenshots/phase-21/. Offline/deterministic. */
import { test, expect, type Page } from '@playwright/test';
import { mkdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '../../screenshots/phase-21');
mkdirSync(OUT, { recursive: true });
const INDEX = join(OUT, 'captures.json');
const log: Record<string, string> = existsSync(INDEX) ? JSON.parse(readFileSync(INDEX, 'utf8')) : {};
async function shot(page: Page, name: string, description: string) {
  await page.locator('.stage-head h1').first().waitFor({ state: 'visible' });
  await page.waitForTimeout(1200);   // let a 3D view that was just left finish tearing down
  await page.screenshot({ path: join(OUT, `${name}.png`), animations: 'disabled' });
  log[`${name}.png`] = description;
  writeFileSync(INDEX, JSON.stringify(log, null, 2));
  const md = ['# Phase 21 screenshots', '', 'Generated by `tests/e2e/phase21.spec.ts` from the running application (Playwright, Chromium + SwiftShader). Not edited.', '',
    ...Object.entries(log).sort(([a], [b]) => a.localeCompare(b)).map(([f, d]) => `- **${f}** — ${d}`), ''].join('\n');
  writeFileSync(join(OUT, 'INDEX.md'), md);
}
const errors: string[] = [];
test.beforeEach(({ page }) => { page.on('pageerror', (e) => errors.push(e.message)); });
test.afterEach(() => { expect(errors, errors.join(' | ')).toEqual([]); });


const fits = async (page: import('@playwright/test').Page) => {
  const bar = await page.locator('header.topbar').boundingBox(), acts = await page.locator('.topbar-actions').boundingBox();
  expect(acts!.x + acts!.width).toBeLessThanOrEqual(bar!.x + bar!.width + 1);
};

test('131 storm laboratory: hurricanes (Saffir-Simpson, ingredients, Katrina), thunderstorm life cycle, EF scale, fronts, wind chill and blizzards, heat index', async ({ page }) => {
  await page.goto('/#/meteorology');
  await page.getByRole('navigation', { name: 'Meteorology sections' }).getByRole('button', { name: 'Weather ▾' }).click();
  await page.getByRole('menuitem', { name: 'Storm laboratory' }).click();
  await expect(page).toHaveURL(/#\/meteorology\/storms$/);
  await fits(page);
  await expect(page.getByLabel('Hurricane category')).toContainText('Category 3 (major)');
  await expect(page.getByLabel('Observed: Hurricane Katrina, 23–30 August 2005')).toContainText('902 mb');
  await shot(page, '131a-hurricane', 'Storm laboratory (Phase 21): a tropical cyclone — NHC definition and stages, Saffir-Simpson category from the wind (100 kt = Category 3), formation ingredients (Penn State and NASA disagree: 5° vs 8° from the equator), and Katrina from the NHC report (150 kt, 902 mb; 1392 deaths in the 2023 update).');
  await page.getByLabel('Maximum sustained wind').fill('150');
  await expect(page.getByLabel('Hurricane category')).toContainText('Category 5');
  await page.getByRole('option', { name: 'Thunderstorm' }).click();
  await page.getByRole('button', { name: /3\. Dissipating/ }).click();
  await expect(page.getByLabel('Stage')).toContainText('downdraft');
  await shot(page, '131b-thunderstorm', 'Thunderstorm life cycle (NWS spotter guide): developing, mature, dissipating — at dissipation the downdraft overcomes the updraft; NSSL’s severe criteria as a check.');
  await page.getByRole('option', { name: 'Tornado' }).click();
  await page.getByLabel('Estimated gust').fill('210');
  await expect(page.getByLabel('EF rating')).toContainText('EF5');
  await page.getByRole('option', { name: 'Blizzard and winter storm' }).click();
  await expect(page.getByLabel('Winter values')).toContainText('no');
  await page.getByLabel('Wind speed').fill('40');
  await expect(page.getByLabel('Winter values')).toContainText('yes');
  await shot(page, '131c-winter', 'Winter storms: NSSL’s snow, sleet and freezing-rain profiles; NWS wind chill (10 °F, 40 mph) and the blizzard criteria (35 mph, ¼ mile, 3 hours).');
  await page.getByRole('option', { name: 'Heat wave' }).click();
  await expect(page.getByLabel('Heat index')).toContainText('Rothfusz');
  await expect(page.getByLabel('Observed: Chicago and the Midwest, July 1995')).toContainText('465');
});

test('132 Earth weather atlas: nineteen labelled layers on a map and a globe, month timeline, wind arrows, point inspector', async ({ page }) => {
  await page.goto('/#/meteorology');
  await page.getByRole('navigation', { name: 'Meteorology sections' }).getByRole('button', { name: 'Weather ▾' }).click();
  await page.getByRole('menuitem', { name: 'Earth weather atlas' }).click();
  await expect(page).toHaveURL(/#\/meteorology\/atlas$/);
  await fits(page);
  const v = page.getByLabel('Atlas values');
  await expect(v).toContainText(/18\.[6-9] °C/, { timeout: 15000 });   // global mean SST, January 2024
  await page.goto('/#/meteorology/atlas?p=0,160');
  await expect(v).toContainText(/2[789]\.\d °C|3[01]\.\d °C/, { timeout: 15000 });
  await shot(page, '132a-sst', 'Earth weather atlas (Gate 21.2): January 2024 sea surface temperature (NOAA OISST v2.1, 1°), area-weighted global mean about 18.8 °C; the inspector reads the warm pool on the equator at 160° E; latitude profile on the right.');
  await page.getByRole('radiogroup', { name: 'Air flow layers' }).getByRole('radio', { name: 'Sea-level pressure' }).click();
  await page.getByRole('radiogroup', { name: 'Wind overlay' }).getByRole('radio', { name: 'Surface' }).click();
  await expect(page.locator('.stage-head')).toContainText('reanalysis climatology');
  await page.getByLabel('Month', { exact: true }).fill('6');
  await expect(page.locator('.stage-head')).toContainText('Jul');
  await shot(page, '132b-pressure-wind', 'July sea-level pressure (1991–2020 mean, NCEP/NCAR Reanalysis 1) with surface wind arrows: subtropical highs, the trade winds and the summer monsoon flow.');
  await page.getByRole('radiogroup', { name: 'Water layers' }).getByRole('radio', { name: 'Precipitation' }).click();
  await page.getByRole('radiogroup', { name: 'Projection' }).getByRole('radio', { name: '3D globe' }).click();
  await expect(page.locator('.atlas-globe canvas')).toBeVisible();
  await page.waitForTimeout(1500);
  await shot(page, '132c-globe', 'The same atlas on a 3D globe: July 2024 precipitation (GPCP v2.3, interim), the rain belt shifted north with the season.');
});

test('133 regional climates: NOAA 1991–2020 climographs, Köppen–Geiger classes step by step, causes compared in pairs, a what-if reclassification', async ({ page }) => {
  await page.goto('/#/meteorology');
  await page.getByRole('navigation', { name: 'Meteorology sections' }).getByRole('button', { name: 'Weather ▾' }).click();
  await page.getByRole('menuitem', { name: 'Regional climates' }).click();
  await expect(page).toHaveURL(/#\/meteorology\/climates$/);
  await fits(page);
  await expect(page.getByLabel('Station A values')).toContainText('Cfb');
  await expect(page.getByLabel('Station B values')).toContainText('BSk');
  await page.getByRole('radiogroup', { name: 'Causes' }).getByRole('radio', { name: 'Mountains and rain shadows' }).click();
  await expect(page.getByLabel('Cause', { exact: true })).toContainText('lee side of a mountain barrier');
  await shot(page, '133a-rainshadow', 'Regional climates (Gate 21.3): the rain shadow — Quillayute on the Olympic coast (2,574 mm a year, Cfb) against Yakima in the lee of the Cascades (204 mm, BSk), from NOAA 1991–2020 normals; Köppen–Geiger classes by Peel et al. (2007).');
  await page.getByRole('radiogroup', { name: 'Causes' }).getByRole('radio', { name: 'Mediterranean climates' }).click();
  await page.getByRole('radiogroup', { name: 'Depth' }).getByRole('radio', { name: 'Understand' }).click();
  await expect(page.getByLabel('Classification steps')).toContainText('BSk');
  await expect(page.locator('.center-stage')).toContainText('just arid');
  await shot(page, '133b-mediterranean', 'Mediterranean summers: Los Angeles and San Francisco, wet winters and dry summers; by Peel’s criteria Los Angeles airport is just arid (BSk), a finding shown beside the National Park Service’s description.');
  await page.getByRole('radiogroup', { name: 'Causes' }).getByRole('radio', { name: 'Height' }).click();
  await expect(page.getByLabel('What-if class')).toContainText('BSk');   // Denver
  await page.getByLabel('Station A', { exact: true }).selectOption('USW00014755');
  await expect(page.getByLabel('What-if class')).toContainText('ET');
  await page.getByLabel('Temperature shift').fill('2');
  await expect(page.getByLabel('What-if class')).toContainText(/With these changes\s*D/);
});
