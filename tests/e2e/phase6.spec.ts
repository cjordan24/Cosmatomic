/** Phase 6 browser verification (Deep Space & Invisible Gravity). Screenshots → screenshots/phase-06/. Offline/deterministic. */
import { test, expect, type Page } from '@playwright/test';
import { mkdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '../../screenshots/phase-06');
mkdirSync(OUT, { recursive: true });
const INDEX = join(OUT, 'captures.json');
const log: Record<string, string> = existsSync(INDEX) ? JSON.parse(readFileSync(INDEX, 'utf8')) : {};
async function shot(page: Page, name: string, description: string) {
  await page.waitForTimeout(700);
  await page.screenshot({ path: join(OUT, `${name}.png`) });
  log[`${name}.png`] = description;
  writeFileSync(INDEX, JSON.stringify(log, null, 2));
  const md = ['# Phase 6 screenshots', '', 'Generated by `tests/e2e/phase6.spec.ts` from the running application (Playwright, Chromium + SwiftShader). Not edited.', '',
    ...Object.entries(log).sort(([a], [b]) => a.localeCompare(b)).map(([f, d]) => `- **${f}** — ${d}`), ''].join('\n');
  writeFileSync(join(OUT, 'INDEX.md'), md);
}
const errors: string[] = [];
test.beforeEach(({ page }) => { page.on('pageerror', (e) => errors.push(e.message)); });
test.afterEach(() => { expect(errors, errors.join(' | ')).toEqual([]); });

// ---------------- Gate 6.1 ----------------
test('59 relativity: Schwarzschild radii and clocks, orbits, light paths, weak-field tests', async ({ page }) => {
  await page.goto('/#/cosmic');
  await page.getByRole('navigation', { name: 'Cosmic sections' }).getByRole('button', { name: 'Relativity' }).click();
  await expect(page).toHaveURL(/#\/cosmic\/relativity$/);
  const info = page.locator('.right-panel');
  await expect(info.getByLabel('Characteristic radii')).toContainText('2.953 km');
  await expect(info).toContainText('no horizon, photon sphere or ISCO');
  await page.getByRole('radio', { name: '10 M☉ black hole' }).check();
  await expect(page).toHaveURL(/m=bh10/);
  await expect(info.getByLabel('Characteristic radii')).toContainText('29.53 km');
  await expect(info.getByLabel('Probe values')).toContainText('0.8660254');
  await expect(page.getByRole('img', { name: 'Characteristic radii to scale' })).toBeVisible();
  await shot(page, '59a-relativity-radii', 'Relativity view (#/cosmic/relativity) for a hypothetical 10 M☉ black hole: static and orbiting clock rates and the gravitational redshift against r/r_s, the horizon, photon sphere and ISCO drawn to scale, and probe values at 4 r_s (static clock √0.75).');
  await page.getByRole('button', { name: 'Orbits' }).click();
  await expect(page.getByRole('img', { name: 'Effective potential for a massive particle' })).toBeVisible();
  await expect(page.locator('main')).toContainText('unstable, potential maximum');
  await shot(page, '59b-relativity-orbits', 'Effective potential (Carroll eq. 7.48) for L̃ = 4 GM/c: general relativity against Newtonian, with the unstable and stable circular orbits marked, and the photon potential peaking at 3GM/c².');
  await page.goto('/#/cosmic/relativity?tab=light&m=bh10&b=2.7');
  await expect(page.getByRole('img', { name: 'Light paths around a non-rotating black hole' })).toBeVisible();
  await expect(info.getByLabel('Selected ray')).toContainText('escaped');
  await shot(page, '59c-relativity-light', 'Numerically integrated null geodesics around a Schwarzschild black hole: rays below b = 3√3 GM/c² are captured, the selected ray at b = 2.7 r_s loops around the photon sphere before escaping.');
  await page.goto('/#/cosmic/relativity?tab=light&m=bh10&b=2.5');
  await expect(info.getByLabel('Selected ray')).toContainText('captured');
  await page.getByRole('button', { name: 'Weak-field tests' }).click();
  const t = page.getByRole('table', { name: 'Weak-field tests' });
  await expect(t).toContainText('42.98″ per century');
  await expect(t).toContainText('1.751″');
  await expect(page.getByLabel('Lorentz factor')).toContainText('1.25');
  await shot(page, '59d-relativity-tests', 'Weak-field checks: Mercury’s relativistic perihelion advance from JPL elements (42.98″ per century vs. the 43″ quoted by Carroll), 1.751″ solar-limb deflection, solar and terrestrial gravitational redshifts, and a Lorentz-factor calculator.');
});
