/** Phase 17 browser verification (Mechanical & Electrical Engineering). Screenshots → screenshots/phase-17/. Offline/deterministic. */
import { test, expect, type Page } from '@playwright/test';
import { mkdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '../../screenshots/phase-17');
mkdirSync(OUT, { recursive: true });
const INDEX = join(OUT, 'captures.json');
const log: Record<string, string> = existsSync(INDEX) ? JSON.parse(readFileSync(INDEX, 'utf8')) : {};
async function shot(page: Page, name: string, description: string) {
  await page.locator('.stage-head h1').first().waitFor({ state: 'visible' });
  await page.waitForTimeout(1200);   // let a 3D view that was just left finish tearing down
  await page.screenshot({ path: join(OUT, `${name}.png`), animations: 'disabled' });
  log[`${name}.png`] = description;
  writeFileSync(INDEX, JSON.stringify(log, null, 2));
  const md = ['# Phase 17 screenshots', '', 'Generated by `tests/e2e/phase17.spec.ts` from the running application (Playwright, Chromium + SwiftShader). Not edited.', '',
    ...Object.entries(log).sort(([a], [b]) => a.localeCompare(b)).map(([f, d]) => `- **${f}** — ${d}`), ''].join('\n');
  writeFileSync(join(OUT, 'INDEX.md'), md);
}
const errors: string[] = [];
test.beforeEach(({ page }) => { page.on('pageerror', (e) => errors.push(e.message)); });
test.afterEach(() => { expect(errors, errors.join(' | ')).toEqual([]); });


test('124 machines and electricity: circuits, mechanisms, engines, the grid, batteries and vehicles, Maxwell’s governor', async ({ page }) => {
  await page.goto('/#/engineering');
  await page.getByRole('navigation', { name: 'Engineering sections' }).getByRole('button', { name: 'Hardware ▾' }).click();
  await page.getByRole('menuitem', { name: 'Machines & electricity' }).click();
  await expect(page).toHaveURL(/#\/engineering\/machines$/);
  const c = page.getByLabel('Circuit values');
  await expect(c).toContainText('90 mA'); await expect(c).toContainText('40.9'); await expect(c).toContainText('19.1');   // 9 V / 100, 220, 470 Ω
  await expect(page.locator('.stage-head')).toContainText('S = A/L');
  await shot(page, '124a-circuits', 'Machines and electricity (Phase 17): a battery and three resistors in parallel — the branch currents (Ohm 1827) add up at the junction (Kirchhoff 1845), both read on the page images.');
  const nav = page.getByRole('navigation', { name: 'Machines sections' });
  await nav.getByRole('button', { name: 'Mechanisms' }).click();
  await expect(page.getByLabel('Gear values')).toContainText('1,000');
  await expect(page.getByLabel('Gear values')).toContainText('30');
  await shot(page, '124b-gears', 'Levers, gears and power: a 12:36 gear pair turns 3000 rpm into 1000 rpm and triples the torque at constant power (Archimedes; Rankine 1869).');
  await nav.getByRole('button', { name: 'Engines' }).click();
  await expect(page.getByLabel('Engine values')).toContainText('62.5 %');
  await expect(page.getByLabel('Otto values')).toContainText('60.2 %');
  await shot(page, '124c-engines', 'Heat engines: Carnot’s 1824 principle and Rankine’s 1859 efficiency (T₁ − T₂)/T₁ (62.5 % between 800 K and 300 K); NASA Glenn’s ideal Otto cycle, 60.2 % at r = 10.');
  await nav.getByRole('button', { name: 'Grid' }).click();
  await expect(page.getByLabel('Generator values')).toContainText('157.1');
  await shot(page, '124d-grid', 'Generators and the grid: a coil turning in a field gives ε = N B A ω sin ωt (Faraday); EIA’s 2025 U.S. generation mix and ~5 % transmission and distribution losses.');
  await nav.getByRole('button', { name: 'Batteries & EVs' }).click();
  await expect(page.getByRole('table', { name: 'Vehicle efficiency' })).toContainText('16–25 %');
  await nav.getByRole('button', { name: 'Control' }).click();
  await expect(page.getByLabel('Root values')).toContainText('It may be an oscillation of continually decreasing amplitude.');
  await page.getByLabel('Damping').fill('-0.3');
  await expect(page.getByLabel('Root values')).toContainText('continually increasing amplitude');
  await shot(page, '124e-governor', 'Feedback: Maxwell’s 1868 governor — with negative damping the disturbance becomes “an oscillation of continually increasing amplitude”, inadmissible in a good governor because a root has a positive real part.');
});
