/** Phase 26 browser verification (Meteorology: validation and usability). Screenshots → screenshots/phase-26/. Offline/deterministic. */
import { test, expect, type Page } from '@playwright/test';
import { mkdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '../../screenshots/phase-26');
mkdirSync(OUT, { recursive: true });
const INDEX = join(OUT, 'captures.json');
const log: Record<string, string> = existsSync(INDEX) ? JSON.parse(readFileSync(INDEX, 'utf8')) : {};
async function shot(page: Page, name: string, description: string) {
  await page.locator('.stage-head h1').first().waitFor({ state: 'visible' });
  await page.waitForTimeout(1200);
  await page.screenshot({ path: join(OUT, `${name}.png`), animations: 'disabled' });
  log[`${name}.png`] = description;
  writeFileSync(INDEX, JSON.stringify(log, null, 2));
  const md = ['# Phase 26 screenshots', '', 'Generated by `tests/e2e/phase26.spec.ts` from the running application (Playwright, Chromium + SwiftShader). Not edited.', '',
    ...Object.entries(log).sort(([a], [b]) => a.localeCompare(b)).map(([f, d]) => `- **${f}** — ${d}`), ''].join('\n');
  writeFileSync(join(OUT, 'INDEX.md'), md);
}
const errors: string[] = [];
test.beforeEach(({ page }) => { page.on('pageerror', (e) => errors.push(e.message)); });
test.afterEach(() => { expect(errors, errors.join(' | ')).toEqual([]); });
const fits = async (page: Page) => {
  const bar = await page.locator('header.topbar').boundingBox(), acts = await page.locator('.topbar-actions').boundingBox();
  expect(acts!.x + acts!.width).toBeLessThanOrEqual(bar!.x + bar!.width + 1);
};

const ROUTES = ['', '/air', '/radiation', '/motion', '/validation', '/atlas', '/storms', '/climates', '/records', '/deeptime', '/iceages', '/oceans', '/human', '/future', '/planets', '/sandbox'];

test('143 model checks: every Meteorology reference check recomputed in the browser, as expected', async ({ page }) => {
  await page.goto('/#/meteorology');
  await page.getByRole('navigation', { name: 'Meteorology sections' }).getByRole('button', { name: 'Atmosphere ▾' }).click();
  await page.getByRole('menuitem', { name: 'Model checks' }).click();
  await expect(page).toHaveURL(/#\/meteorology\/validation$/);
  await fits(page);
  await expect(page.getByLabel('Check summary')).toContainText('all as expected');
  await expect(page.getByLabel('Status t-pluto')).toContainText('source disagrees');
  await expect(page.locator('[aria-label^="Status "]', { hasText: '✗' })).toHaveCount(0);
  await shot(page, '143-model-checks', 'Model checks (Phase 26): 30 reference examples — USSA 1976, NSSDCA gravity, sunlight, black-body temperatures and scale heights for five worlds, Rose’s 303 K, insolation S₀/4, the carbon budget, EDGAR, waste heat, cement, PMEL, sea ice, NCA5 and Sweet — recomputed in the browser; one recorded source disagreement (NSSDCA Pluto).');
});

test.describe('phone', () => {
  test.use({ viewport: { width: 390, height: 844 } });
  test('144 phone: every Meteorology view is reachable from the ☰ menu and none overflows sideways', async ({ page }) => {
    await page.goto('/#/meteorology');
    await page.getByRole('button', { name: 'More' }).click();
    const menu = page.getByRole('menu', { name: 'More' });
    await expect(menu.getByRole('menuitem', { name: /Future climate/ })).toBeVisible();
    await menu.getByRole('menuitem', { name: /Sandbox/ }).click();
    await expect(page).toHaveURL(/#\/meteorology\/sandbox$/);
    await shot(page, '144a-phone-sandbox', 'Phone (390 × 844): the environmental sandbox opened from the ☰ menu, which now lists all Meteorology views.');
    for (const r of ROUTES) {
      await page.goto(`/#/meteorology${r}`);
      await page.locator('.stage-head h1').first().waitFor({ state: 'visible' });
      const over = Number(await page.evaluate('document.documentElement.scrollWidth - window.innerWidth'));
      expect(over, `/meteorology${r} overflows by ${over}px`).toBeLessThanOrEqual(1);
    }
  });
});
