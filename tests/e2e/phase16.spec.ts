/** Phase 16 browser verification (Machine Learning & AI). Screenshots → screenshots/phase-16/. Offline/deterministic. */
import { test, expect, type Page } from '@playwright/test';
import { mkdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '../../screenshots/phase-16');
mkdirSync(OUT, { recursive: true });
const INDEX = join(OUT, 'captures.json');
const log: Record<string, string> = existsSync(INDEX) ? JSON.parse(readFileSync(INDEX, 'utf8')) : {};
async function shot(page: Page, name: string, description: string) {
  await page.locator('.stage-head h1').first().waitFor({ state: 'visible' });
  await page.waitForTimeout(1200);   // let a 3D view that was just left finish tearing down
  await page.screenshot({ path: join(OUT, `${name}.png`), animations: 'disabled' });
  log[`${name}.png`] = description;
  writeFileSync(INDEX, JSON.stringify(log, null, 2));
  const md = ['# Phase 16 screenshots', '', 'Generated by `tests/e2e/phase16.spec.ts` from the running application (Playwright, Chromium + SwiftShader). Not edited.', '',
    ...Object.entries(log).sort(([a], [b]) => a.localeCompare(b)).map(([f, d]) => `- **${f}** — ${d}`), ''].join('\n');
  writeFileSync(join(OUT, 'INDEX.md'), md);
}
const errors: string[] = [];
test.beforeEach(({ page }) => { page.on('pageerror', (e) => errors.push(e.message)); });
test.afterEach(() => { expect(errors, errors.join(' | ')).toEqual([]); });


test('123 AI: timeline, a network trained live, attention, model families, coding agents, energy', async ({ page }) => {
  await page.goto('/#/engineering');
  await page.getByRole('navigation', { name: 'Engineering sections' }).getByRole('button', { name: 'AI ▾' }).click();
  await page.getByRole('menuitem', { name: 'History' }).click();
  await expect(page).toHaveURL(/#\/engineering\/ai$/);
  const bar = await page.locator('header.topbar').boundingBox(), acts = await page.locator('.topbar-actions').boundingBox();
  expect(acts!.x + acts!.width).toBeLessThanOrEqual(bar!.x + bar!.width + 1);
  await expect(page.getByRole('list', { name: 'AI timeline' })).toContainText('Can machines think');
  await expect(page.getByRole('list', { name: 'AI timeline' })).toContainText('175 billion parameters');
  await shot(page, '123a-history', 'AI history (Phase 16): documented results, predictions and conjectures kept apart — Cauchy’s gradient descent (1847), Turing (1950), Dartmouth (1955), the perceptron, Adaline, GANs, the Transformer, scaling laws, GPT-3, diffusion models, the GPT-4 report’s withheld details, Llama 3.');
  const nav = page.getByRole('navigation', { name: 'AI sections' });
  await nav.getByRole('button', { name: 'Training' }).click();
  await page.getByRole('button', { name: 'Train', exact: true }).click();
  await expect.poll(async () => Number((await page.getByLabel('Training values').innerText()).match(/Accuracy\s*(\d+)/)?.[1] ?? 0), { timeout: 60000 }).toBeGreaterThan(90);
  await page.getByRole('button', { name: 'Pause', exact: true }).click();
  await shot(page, '123b-learning', 'Train a network: a 2-8-1 network learns the XOR quadrants by gradient descent and backpropagation, live in the browser — the decision map and the falling loss (Cauchy 1847; Widrow & Hoff 1960; d2l.ai).');
  await nav.getByRole('button', { name: 'Attention' }).click();
  await expect(page.locator('.stage-head')).toContainText('softmax(QKᵀ/√d_k)V');
  await shot(page, '123c-attention', 'Attention & scaling: Vaswani et al.’s eq. (1) computed on a short sentence; Kaplan et al.’s L(N) = (N_c/N)^0.076.');
  await nav.getByRole('button', { name: 'Models' }).click();
  await expect(page.getByRole('region', { name: 'GPT (OpenAI)' })).toContainText('withheld');
  await expect(page.getByRole('region', { name: 'Llama (Meta)' })).toContainText('405B');
  await shot(page, '123d-models', 'Model families: what Anthropic, Google DeepMind, OpenAI and Meta each disclose in their own documents, and what they do not.');
  await nav.getByRole('button', { name: 'Agents' }).click();
  await page.getByRole('button', { name: '6. Verify' }).click();
  await expect(page.getByRole('region', { name: 'Current step' })).toContainText('runs the tests');
  await shot(page, '123e-agents', 'How a coding agent works: an educational step-through from public documentation (Claude Code docs; Model Context Protocol specification) — gather context, act, verify, with permissions and a context window.');
  await nav.getByRole('button', { name: 'Energy' }).click();
  await expect(page.getByLabel('Energy values')).toContainText('240 kWh');      // 0.24 Wh × 10⁶ prompts
  await shot(page, '123f-energy', 'Energy and AI: Google’s company-reported 0.24 Wh per median Gemini text prompt, an independent 0.42 Wh estimate for GPT-4o, and Luccioni et al.’s measured kWh per 1,000 inferences across ten tasks — with a calculator whose assumptions are the user’s.');
});
