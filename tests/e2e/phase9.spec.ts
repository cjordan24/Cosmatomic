test('79 antennas: dipole near/far field, patterns checked against Ellingson, arrays and the Friis link', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('/#/spectral');
  await page.getByRole('navigation', { name: 'Spectral sections' }).getByRole('button', { name: 'Radio ▾' }).click();
  await page.getByRole('menuitem', { name: 'Antennas & fields' }).click();
  await expect(page).toHaveURL(/#\/spectral\/antennas$/);
  await expect(page.getByRole('heading', { name: /A radiating dipole/ })).toBeVisible();
  const canvas = page.getByLabel('Field of a Hertzian dipole');
  const box = (await canvas.boundingBox())!;
  await canvas.click({ position: { x: box.width * 0.82, y: box.height * 0.5 } });
  const probe = page.getByRole('definition').filter({ hasText: 'Ω' }).first();
  await expect(page.getByLabel('Field at the probe point')).toContainText('|E|/|H|');
  await expect(probe).toBeVisible();
  // far away the ratio is the impedance of free space
  await page.goto('/#/spectral/antennas?w=6&px=5.5&py=0');
  await expect(page.getByLabel('Field at the probe point')).toContainText('radiating terms dominate');
  await expect(page.getByLabel('Field at the probe point')).toContainText(/\|E\|\/\|H\|376\.\d Ω/);
  await page.goto('/#/spectral/antennas?px=0.6&py=0.4');
  await shot(page, '79a-dipole-field', 'Exact field of a Hertzian dipole at 100 MHz: H out of/into the plane (colour), E direction (arrows), r = λ/2π (dashed); probe shows E_r, E_θ, H_φ and |E|/|H| (Ellingson eqs. 9.61, 9.65).');

  await page.getByRole('navigation', { name: 'Antenna sections' }).getByRole('button', { name: 'Dipole patterns' }).click();
  const fig = page.getByRole('table', { name: 'Antenna figures' });
  await expect(fig).toContainText('73.08 Ω');
  await expect(fig).toContainText('0.1306 λ²');
  await expect(fig).toContainText('1.641 (2.15');
  await expect(page.getByRole('img', { name: 'E-plane radiation pattern' })).toBeVisible();
  await shot(page, '79b-dipole-patterns', 'Half-wave dipole: E- and H-plane patterns, 3D field pattern; numerically integrated D = 1.641, R_rad = 73.08 Ω, A_e = 0.1306 λ² beside Ellingson’s ≅ 73 Ω and ≈ 0.131 λ².');
  await page.getByRole('radio', { name: 'Electrically short dipole' }).click();
  await expect(fig).toContainText('1.5 (1.76 dBi)');
  await expect(fig).toContainText(/1\.50\d \(1\.76/);

  await page.getByRole('navigation', { name: 'Antenna sections' }).getByRole('button', { name: 'Arrays' }).click();
  await page.getByLabel('Element spacing in wavelengths').fill('1.5');
  await expect(page.getByRole('status').filter({ hasText: 'Grating lobes' })).toBeVisible();
  await page.goto('/#/spectral/antennas?tab=array&N=8&d=0.5&a=-90');
  await expect(page.getByLabel('Array quantities')).toContainText('60°');
  await shot(page, '79c-array', 'Eight half-wave dipoles at λ/2 with a −90° phase step: the beam is steered to φ = 60° from the array axis (pattern multiplication, no mutual coupling).');

  await page.getByRole('navigation', { name: 'Antenna sections' }).getByRole('button', { name: 'Radio link' }).click();
  await page.getByRole('button', { name: /Ellingson Example 10\.11/ }).click();
  await expect(page.getByLabel('Link quantities')).toContainText('-120.05 dBm');
  await shot(page, '79d-friis', 'Friis link: Ellingson Example 10.11 (6 GHz, 30 km, 27 dBi dishes, −36.5 dBm transmitted) gives −120.05 dBm at the receiver with the exact c.');
});

