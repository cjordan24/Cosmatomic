/** Phase 15 browser verification (Computing & Computer Engineering). Screenshots → screenshots/phase-15/. Offline/deterministic. */
import { test, expect, type Page } from '@playwright/test';
import { mkdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '../../screenshots/phase-15');
mkdirSync(OUT, { recursive: true });
const INDEX = join(OUT, 'captures.json');
const log: Record<string, string> = existsSync(INDEX) ? JSON.parse(readFileSync(INDEX, 'utf8')) : {};
async function shot(page: Page, name: string, description: string) {
  await page.locator('.stage-head h1').first().waitFor({ state: 'visible' });
  await page.waitForTimeout(1200);   // let a 3D view that was just left finish tearing down
  await page.screenshot({ path: join(OUT, `${name}.png`), animations: 'disabled' });
  log[`${name}.png`] = description;
  writeFileSync(INDEX, JSON.stringify(log, null, 2));
  const md = ['# Phase 15 screenshots', '', 'Generated by `tests/e2e/phase15.spec.ts` from the running application (Playwright, Chromium + SwiftShader). Not edited.', '',
    ...Object.entries(log).sort(([a], [b]) => a.localeCompare(b)).map(([f, d]) => `- **${f}** — ${d}`), ''].join('\n');
  writeFileSync(join(OUT, 'INDEX.md'), md);
}
const errors: string[] = [];
test.beforeEach(({ page }) => { page.on('pageerror', (e) => errors.push(e.message)); });
test.afterEach(() => { expect(errors, errors.join(' | ')).toEqual([]); });


// ---------------- Gate 15.1 ----------------
test('116 engineering mode: portal, bits, gates and a ripple-carry adder', async ({ page }) => {
  await page.goto('/#/');
  await page.getByRole('button', { name: 'Enter Engineering mode' }).click();
  await expect(page).toHaveURL(/#\/engineering$/);
  const bar = await page.locator('header.topbar').boundingBox(), acts = await page.locator('.topbar-actions').boundingBox();
  expect(acts!.x + acts!.width).toBeLessThanOrEqual(bar!.x + bar!.width + 1);
  const v = page.getByLabel('Byte values');
  await expect(v).toContainText('00101010'); await expect(v).toContainText('0x2A');
  await page.getByRole('button', { name: 'Bit worth 128' }).click();
  await expect(v).toContainText('10101010'); await expect(v).toContainText('-86');   // 170 as a signed byte
  await expect(page.locator('.stage-head')).toContainText('a word suggested by J. W. Tukey');
  await expect(page.getByRole('table', { name: 'Binary prefixes' })).toContainText('1,048,576');
  await shot(page, '116a-bits', 'Engineering mode (Gate 15.1): one byte in binary, hexadecimal and two’s complement — click a bit to flip it; Shannon’s 1948 naming of the bit; NIST’s binary prefixes.');
  const nav = page.getByRole('navigation', { name: 'Logic sections' });
  await nav.getByRole('button', { name: 'Logic gates' }).click();
  await page.getByRole('button', { name: 'XOR', exact: true }).click();
  await expect(page.getByLabel('Gate output')).toContainText('1');          // XOR(1, 0)
  await expect(page.locator('.stage-head')).toContainText('x² = x');
  await expect(page.locator('.stage-head')).toContainText('a perfect analogy exists between the calculus for switching circuits');
  await shot(page, '116b-gates', 'Logic gates: XOR with live inputs and its truth table; NAND alone rebuilding NOT, AND, OR and XOR; Boole’s x² = x (1854) and Shannon’s switching-circuit analogy (1938, with his hindrance convention).');
  await nav.getByRole('button', { name: 'Adding' }).click();
  await expect(page.getByLabel('Adder result')).toContainText('21 = 10101');
  await shot(page, '116c-adder', 'Adding with gates: 9 + 12 through a 4-bit ripple-carry adder — every carry and sum bit computed by the gates; the answer needs a fifth bit.');
});
