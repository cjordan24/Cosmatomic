/** Phase 11 browser verification (Biologic Foundations). Screenshots → screenshots/phase-11/. Offline/deterministic. */
import { test, expect, type Page } from '@playwright/test';
import { mkdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '../../screenshots/phase-11');
mkdirSync(OUT, { recursive: true });
const INDEX = join(OUT, 'captures.json');
const log: Record<string, string> = existsSync(INDEX) ? JSON.parse(readFileSync(INDEX, 'utf8')) : {};
async function shot(page: Page, name: string, description: string) {
  await page.waitForTimeout(700);
  await page.screenshot({ path: join(OUT, `${name}.png`) });
  log[`${name}.png`] = description;
  writeFileSync(INDEX, JSON.stringify(log, null, 2));
  const md = ['# Phase 11 screenshots', '', 'Generated by `tests/e2e/phase11.spec.ts` from the running application (Playwright, Chromium + SwiftShader). Not edited.', '',
    ...Object.entries(log).sort(([a], [b]) => a.localeCompare(b)).map(([f, d]) => `- **${f}** — ${d}`), ''].join('\n');
  writeFileSync(join(OUT, 'INDEX.md'), md);
}
const errors: string[] = [];
test.beforeEach(({ page }) => { page.on('pageerror', (e) => errors.push(e.message)); });
test.afterEach(() => { expect(errors, errors.join(' | ')).toEqual([]); });

// ---------------- Gate 11.1 ----------------
test('94 biologic: landing portal with 1BNA, scale of life from water to an ant, quotes, disagreeing sources and a size ratio', async ({ page }) => {
  await page.goto('/#/');
  await page.waitForTimeout(1500);
  await page.getByRole('button', { name: 'Enter Biologic mode' }).click();
  await expect(page).toHaveURL(/#\/biologic$/);
  await expect(page.locator('.center-stage h1')).toContainText('Scale of life');
  await expect(page.locator('nav.mode-switch button.biologic')).toHaveClass(/active/);
  await expect(page.getByRole('img', { name: 'Scale of life: sizes on a logarithmic axis' })).toBeVisible();
  await expect(page.locator('.life-item')).toHaveCount(24);
  // the top bar still fits in 1440 px with a fourth mode
  const bar = await page.locator('header.topbar').boundingBox();
  const actions = await page.locator('.topbar-actions').boundingBox();
  expect(actions!.x + actions!.width).toBeLessThanOrEqual(bar!.x + bar!.width + 1);
  await shot(page, '94a-scale-of-life', 'Scale of life (Gate 11.1): 24 sizes from a water molecule (derived from its PubChem3D conformer) to an ant on one log axis, quoted from NIGMS Inside the Cell, NIGMS Biomedical Beat, nano.gov, the U.S. DOE Scale of Things chart and the PDB-101 virus flyer.');
  // DNA: two sources disagree (2 nm vs 2.5 nm) and both are shown
  await page.getByRole('list', { name: 'All sizes, smallest first' }).getByRole('button', { name: /DNA double helix/ }).click();
  const reports = page.getByRole('list', { name: 'Reported sizes' });
  await expect(reports).toContainText('≈ 2 nm');
  await expect(reports).toContainText('2.5 nm');
  await expect(reports).toContainText('A strand of human DNA is 2.5 nanometers in diameter.');
  await expect(page.locator('.warn-note')).toContainText('The sources give different values');
  // human egg from Inside the Cell p. 20; compare with a red blood cell
  await page.goto('/#/biologic?sel=red-blood-cell&cmp=human-egg');
  await expect(page.getByRole('list', { name: 'Reported sizes' })).toContainText('Red blood cells (~7-8 µm)');
  const cmp = page.getByRole('region', { name: 'Size comparison' });
  await expect(cmp).toContainText('Human egg cell (150 µm)');
  await expect(cmp).toContainText('20 ×');   // 150 / √(7·8) = 20.04
  await shot(page, '94b-egg-vs-red-cell', 'A red blood cell (~7–8 µm, DOE chart) compared with the human egg (150 µm, Inside the Cell p. 20): the egg is about 20 times wider (the range counts as its geometric mean).');
  // mitochondrion links to the registry; the scale navigator links back
  await page.goto('/#/biologic?sel=mitochondrion');
  await expect(page.getByRole('list', { name: 'Reported sizes' })).toContainText('Typically 1–2 micrometers but can be up to 7 micrometers long');
  await page.getByRole('button', { name: 'See it in the scale navigator →' }).click();
  await expect(page).toHaveURL(/#\/scale\?z=/);
  // portal screenshot
  await page.goto('/#/');
  await page.waitForTimeout(2000);
  await shot(page, '94c-landing-biologic', 'The landing page with the live BIOLOGIC portal: the 486 atoms of the B-DNA dodecamer 1BNA (Drew et al. 1981, PDB CC0) coloured by element.');
});

// ---------------- Gate 11.2 ----------------
test('95 biomolecules: amino acids with IUPAC symbols and codons, nucleic-acid parts, the NCBI genetic codes and a translation', async ({ page }) => {
  await page.goto('/#/biologic');
  await page.getByRole('navigation', { name: 'Biologic sections' }).getByRole('button', { name: 'Biomolecules' }).click();
  await expect(page).toHaveURL(/#\/biologic\/molecules$/);
  await expect(page.locator('.center-stage h1')).toContainText('Amino acids');
  await expect(page.getByRole('list', { name: 'Amino acids cards' }).getByRole('listitem')).toHaveCount(20);
  await expect(page.locator('blockquote[data-term="Amino Acids"]')).toContainText('There are 20 different amino acids.');
  await page.getByRole('list', { name: 'Amino acids cards' }).getByRole('listitem', { name: 'L-leucine' }).click();
  const codons = page.getByRole('region', { name: 'Codons' });
  await expect(codons).toContainText('Codons in the standard code (6)');
  await expect(codons).toContainText('UUA UUG CUU CUC CUA CUG');
  await expect(page.getByLabel('Molecule facts')).toContainText('Leu · L');
  await page.waitForTimeout(1200);
  await shot(page, '95a-amino-acids', 'The 20 amino acids (Gate 11.2): IUPAC-IUB one- and three-letter symbols, the bundled PubChem3D conformers, ChEBI descriptions and, for leucine, its six codons in NCBI’s standard code.');
  await page.getByRole('navigation', { name: 'Biomolecule sections' }).getByRole('button', { name: 'Nucleic-acid parts' }).click();
  await expect(page.locator('blockquote[data-term="Base Pair"]')).toContainText('adenine pairs with thymine, and cytosine pairs with guanine');
  await expect(page.getByRole('list', { name: 'Nucleic-acid parts cards' }).getByRole('listitem')).toHaveCount(9);
  // genetic code
  await page.getByRole('navigation', { name: 'Biomolecule sections' }).getByRole('button', { name: 'Genetic code' }).click();
  await expect(page.getByRole('table', { name: /Codon table: The Standard Code/ })).toBeVisible();
  await expect(page.locator('.stage-head')).toContainText('61 codons specify amino acids and 3 are stops');
  await expect(page.getByLabel('Protein (one-letter)')).toHaveText('REFA');   // 1BNA strand, frame 1
  await page.getByLabel('Sequence to translate').fill('ATGGCCATTGTAATGGGCCGCTGA');
  await expect(page.getByLabel('Protein (one-letter)')).toHaveText('MAIVMGR*');
  await expect(page.getByLabel('Protein (three-letter)')).toContainText('Met–Ala–Ile–Val–Met–Gly–Arg–Stop');
  await shot(page, '95b-genetic-code', 'NCBI’s Standard Code as a codon table (stops red, possible starts outlined) translating ATGGCCATTGTAATGGGCCGCTGA to MAIVMGR* in frame 1; amber marks the four codons read differently in vertebrate mitochondria.');
  await page.getByRole('group', { name: 'Genetic code' }).getByRole('button', { name: 'Vertebrate mitochondrial (2)' }).click();
  await expect(page.locator('.stage-head')).toContainText('60 codons specify amino acids and 4 are stops');
  await expect(page.getByLabel('Protein (one-letter)')).toHaveText('MAIVMGRW');   // UGA reads Trp in vertebrate mitochondria
  await page.locator('.codon[data-codon="AUG"]').click();
  await expect(page.getByLabel('Codons per amino acid')).toContainText('Met');
  await expect(page.locator('.right-panel')).toContainText('Codons in this code');
});
