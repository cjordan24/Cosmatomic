test('94 biologic: landing portal with 1BNA, scale of life from water to an ant, quotes, disagreeing sources and a size ratio', async ({ page }) => {
  await page.goto('/#/');
  await page.waitForTimeout(1500);
  await page.getByRole('button', { name: 'Enter Biologic mode' }).click();
  await expect(page).toHaveURL(/#\/biologic$/);
  await expect(page.locator('.center-stage h1')).toContainText('Scale of life');
  await expect(page.locator('nav.mode-switch button.biologic')).toHaveClass(/active/);
  await expect(page.getByRole('img', { name: 'Scale of life: sizes on a logarithmic axis' })).toBeVisible();
  await expect(page.locator('.life-item')).toHaveCount(24);
  // the top bar still fits in 1440 px with a fourth mode
  const bar = await page.locator('header.topbar').boundingBox();
  const actions = await page.locator('.topbar-actions').boundingBox();
  expect(actions!.x + actions!.width).toBeLessThanOrEqual(bar!.x + bar!.width + 1);
  await shot(page, '94a-scale-of-life', 'Scale of life (Gate 11.1): 24 sizes from a water molecule (derived from its PubChem3D conformer) to an ant on one log axis, quoted from NIGMS Inside the Cell, NIGMS Biomedical Beat, nano.gov, the U.S. DOE Scale of Things chart and the PDB-101 virus flyer.');
  // DNA: two sources disagree (2 nm vs 2.5 nm) and both are shown
  await page.getByRole('list', { name: 'All sizes, smallest first' }).getByRole('button', { name: /DNA double helix/ }).click();
  const reports = page.getByRole('list', { name: 'Reported sizes' });
  await expect(reports).toContainText('≈ 2 nm');
  await expect(reports).toContainText('2.5 nm');
  await expect(reports).toContainText('A strand of human DNA is 2.5 nanometers in diameter.');
  await expect(page.locator('.warn-note')).toContainText('The sources give different values');
  // human egg from Inside the Cell p. 20; compare with a red blood cell
  await page.goto('/#/biologic?sel=red-blood-cell&cmp=human-egg');
  await expect(page.getByRole('list', { name: 'Reported sizes' })).toContainText('Red blood cells (~7-8 µm)');
  const cmp = page.getByRole('region', { name: 'Size comparison' });
  await expect(cmp).toContainText('Human egg cell (150 µm)');
  await expect(cmp).toContainText('20 ×');   // 150 / √(7·8) = 20.04
  await shot(page, '94b-egg-vs-red-cell', 'A red blood cell (~7–8 µm, DOE chart) compared with the human egg (150 µm, Inside the Cell p. 20): the egg is about 20 times wider (the range counts as its geometric mean).');
  // mitochondrion links to the registry; the scale navigator links back
  await page.goto('/#/biologic?sel=mitochondrion');
  await expect(page.getByRole('list', { name: 'Reported sizes' })).toContainText('Typically 1–2 micrometers but can be up to 7 micrometers long');
  await page.getByRole('button', { name: 'See it in the scale navigator →' }).click();
  await expect(page).toHaveURL(/#\/scale\?z=/);
  // portal screenshot
  await page.goto('/#/');
  await page.waitForTimeout(2000);
  await shot(page, '94c-landing-biologic', 'The landing page with the live BIOLOGIC portal: the 486 atoms of the B-DNA dodecamer 1BNA (Drew et al. 1981, PDB CC0) coloured by element.');
});

