/** Phase 19 browser verification (Integrated Systems). Screenshots → screenshots/phase-19/. Offline/deterministic. */
import { test, expect, type Page } from '@playwright/test';
import { mkdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '../../screenshots/phase-19');
mkdirSync(OUT, { recursive: true });
const INDEX = join(OUT, 'captures.json');
const log: Record<string, string> = existsSync(INDEX) ? JSON.parse(readFileSync(INDEX, 'utf8')) : {};
async function shot(page: Page, name: string, description: string) {
  await page.locator('.stage-head h1').first().waitFor({ state: 'visible' });
  await page.waitForTimeout(1200);   // let a 3D view that was just left finish tearing down
  await page.screenshot({ path: join(OUT, `${name}.png`), animations: 'disabled' });
  log[`${name}.png`] = description;
  writeFileSync(INDEX, JSON.stringify(log, null, 2));
  const md = ['# Phase 19 screenshots', '', 'Generated by `tests/e2e/phase19.spec.ts` from the running application (Playwright, Chromium + SwiftShader). Not edited.', '',
    ...Object.entries(log).sort(([a], [b]) => a.localeCompare(b)).map(([f, d]) => `- **${f}** — ${d}`), ''].join('\n');
  writeFileSync(join(OUT, 'INDEX.md'), md);
}
const errors: string[] = [];
test.beforeEach(({ page }) => { page.on('pageerror', (e) => errors.push(e.message)); });
test.afterEach(() => { expect(errors, errors.join(' | ')).toEqual([]); });


test('126 build a system: a spacecraft from power to bits, a chatbot service from power plant to chip, an electric car, and the map of eight systems', async ({ page }) => {
  await page.goto('/#/engineering');
  await page.getByRole('navigation', { name: 'Engineering sections' }).getByRole('button', { name: 'Hardware ▾' }).click();
  await page.getByRole('menuitem', { name: 'Build a system' }).click();
  await expect(page).toHaveURL(/#\/engineering\/systems$/);
  const b = page.getByLabel('Spacecraft budget');
  await expect(b).toContainText('474 W'); await expect(b).toContainText('362 kbit/s');
  await expect(page.locator('.center-stage')).toContainText('275 bit/s');
  await shot(page, '126a-spacecraft', 'Build a system (Phase 19): three RTGs, a 20 W transmitter and Voyager’s 3.7 m dish at Jupiter’s distance give 362 kbit/s into a 70 m dish by Yuen’s link equations and Voyager’s coding requirement; the same chain at Voyager 1’s 2024 distance gives 275 bit/s, against the real 160 bit/s.');
  await page.getByRole('radiogroup', { name: 'Destination' }).getByRole('radio', { name: /Voyager 1/ }).click();
  await page.getByRole('radiogroup', { name: 'Power source' }).getByRole('radio', { name: 'Solar arrays' }).click();
  await expect(b).toContainText('0.204 W');
  await expect(page.getByText('The transmitter alone needs more than the supply provides')).toBeVisible();
  const nav = page.getByRole('navigation', { name: 'Systems sections' });
  await nav.getByRole('button', { name: 'Data centre' }).click();
  const d = page.getByLabel('Data centre budget');
  await expect(d).toContainText('253,000'); await expect(d).toContainText('0.0922');
  await shot(page, '126b-datacentre', 'From power plant to prompt: a billion prompts a day at Google’s 0.24 Wh each, LBNL’s AI-facility PUE of 1.145 and EIA’s 5 % grid losses — 253,000 kWh generated a day, 0.092 TWh a year.');
  await nav.getByRole('button', { name: 'Electric car' }).click();
  await expect(page.getByLabel('EV budget')).toContainText('67.5');
  await expect(page.getByLabel('EV budget')).toContainText('45.2');
  await shot(page, '126c-ev', 'Battery to wheels: 150 L of 2020 lithium-ion cells (450 Wh/L, DOE) store 67.5 kWh; 67 % reaches the wheels (DOE).');
  await nav.getByRole('button', { name: 'All systems' }).click();
  await expect(page.getByRole('table', { name: 'Systems map' })).toContainText('A scientific spacecraft');
  await shot(page, '126d-map', 'Eight systems from the brief, the views that hold their parts and what flows through each.');
});
