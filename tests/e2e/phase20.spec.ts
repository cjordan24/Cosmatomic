/** Phase 20 browser verification (Meteorology: atmospheric physics). Screenshots → screenshots/phase-20/. Offline/deterministic. */
import { test, expect, type Page } from '@playwright/test';
import { mkdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '../../screenshots/phase-20');
mkdirSync(OUT, { recursive: true });
const INDEX = join(OUT, 'captures.json');
const log: Record<string, string> = existsSync(INDEX) ? JSON.parse(readFileSync(INDEX, 'utf8')) : {};
async function shot(page: Page, name: string, description: string) {
  await page.locator('.stage-head h1').first().waitFor({ state: 'visible' });
  await page.waitForTimeout(1200);   // let a 3D view that was just left finish tearing down
  await page.screenshot({ path: join(OUT, `${name}.png`), animations: 'disabled' });
  log[`${name}.png`] = description;
  writeFileSync(INDEX, JSON.stringify(log, null, 2));
  const md = ['# Phase 20 screenshots', '', 'Generated by `tests/e2e/phase20.spec.ts` from the running application (Playwright, Chromium + SwiftShader). Not edited.', '',
    ...Object.entries(log).sort(([a], [b]) => a.localeCompare(b)).map(([f, d]) => `- **${f}** — ${d}`), ''].join('\n');
  writeFileSync(join(OUT, 'INDEX.md'), md);
}
const errors: string[] = [];
test.beforeEach(({ page }) => { page.on('pageerror', (e) => errors.push(e.message)); });
test.afterEach(() => { expect(errors, errors.join(' | ')).toEqual([]); });


const fits = async (page: import('@playwright/test').Page) => {
  const bar = await page.locator('header.topbar').boundingBox(), acts = await page.locator('.topbar-actions').boundingBox();
  expect(acts!.x + acts!.width).toBeLessThanOrEqual(bar!.x + bar!.width + 1);
};

test('127 meteorology: a sixth portal, the U.S. Standard Atmosphere 1976 profile, layers, composition and the depth switch', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Enter Meteorology mode' }).click();
  await expect(page).toHaveURL(/#\/meteorology$/);
  await fits(page);
  const v = page.getByLabel('Air at this height');
  await expect(v).toContainText('288.15 K'); await expect(v).toContainText('1,013'); await expect(v).toContainText('1.225');
  await shot(page, '127a-structure', 'Meteorology (Phase 20): the U.S. Standard Atmosphere 1976 evaluated from its own layer table — temperature and pressure to 86 km, a box of air thinning with height, NWS and FAA layer definitions and USSA Table 3 composition (with NOAA’s 2025 CO₂ beside the 1970s value).');
  await page.getByRole('button', { name: 'Ozone layer (25 km)' }).click();
  await expect(v).toContainText('stratosphere');
  await page.getByRole('radiogroup', { name: 'Depth' }).getByRole('radio', { name: 'Research' }).click();
  await expect(page.getByRole('table', { name: 'Layer table' })).toContainText('216.65');
  await shot(page, '127b-research', 'Research depth at 25 km: the standard’s pressure equations (33a/b), its scale-height warning, the R* misprint in Table 2 and Humphreys’ 1920 homogeneous atmosphere (7991 m) against 7995 m from the 1976 constants.');
  await page.goto('/#/cosmic'); await fits(page);
});

test('128 moist air: saturation vapour pressure, dew point and the FAA cloud-base rule; parcel stability by the NWS definitions', async ({ page }) => {
  await page.goto('/#/meteorology');
  await page.getByRole('navigation', { name: 'Meteorology sections' }).getByRole('button', { name: 'Moist air' }).click();
  await expect(page).toHaveURL(/#\/meteorology\/air$/);
  const m = page.getByLabel('Moisture values');
  await expect(m).toContainText('31.69'); await expect(m).toContainText('16.7'); await expect(m).toContainText('3,400 ft');
  await shot(page, '128a-humidity', 'Water in the air: at 25 °C and 60 % the NWS formula gives e_s 31.69 hPa and a dew point of 16.7 °C; the FAA rule puts the cloud base of lifted air near 3,400 ft (1,040 m).');
  await page.getByRole('navigation', { name: 'Moist air sections' }).getByRole('button', { name: 'Stability' }).click();
  const s = page.getByLabel('Stability values');
  await expect(s).toContainText('Conditionally unstable');
  await page.getByLabel('Environmental lapse rate').fill('10.5');
  await expect(s).toContainText('Absolutely unstable');
  await shot(page, '128b-stability', 'Stability: a parcel lifted at the NWS dry rate of 9.8 °C/km to its cloud base, then at a moist rate in the FAA’s range — with the environment cooling 10.5 °C/km it is absolutely unstable by the NWS definition.');
});

test('129 radiation: NASA’s energy budget, NASA TN D-1850 absorption bands, CO₂ forcing (NOAA AGGI), ozone and aerosols', async ({ page }) => {
  await page.goto('/#/meteorology/radiation');
  await expect(page.getByLabel('Balance values')).toContainText('255.1');
  await expect(page.getByRole('img', { name: 'Energy budget diagram' })).toContainText('340.4');
  await shot(page, '129a-budget', 'Earth’s energy budget (NASA, after Loeb 2009 and Trenberth 2009): 340.4 W/m² in, 99.9 reflected, 239.9 out as infrared; the effective temperature computes to 255.1 K against the fact sheet’s 254.0 K.');
  const nav = page.getByRole('navigation', { name: 'Radiation sections' });
  await nav.getByRole('button', { name: 'Absorption' }).click();
  await expect(page.getByRole('table', { name: 'Absorption bands' })).toContainText('14–16');
  await shot(page, '129b-bands', 'Which gases trap heat: NASA TN D-1850’s bands of water vapour, ozone and CO₂ under a 288 K Planck curve, with the window near 10 µm.');
  await nav.getByRole('button', { name: 'Greenhouse forcing' }).click();
  const f = page.getByLabel('Forcing values');
  await expect(f).toContainText('2.37'); await expect(f).toContainText('2.24');
  await shot(page, '129c-forcing', 'Greenhouse forcing: NOAA’s 2025 AGGI by gas (3.59 W/m² in total); at 425.62 ppm the AR6 expression gives 2.37 W/m² for CO₂ and the simple 5.35 ln(C/280) gives 2.24.');
  await nav.getByRole('button', { name: 'Ozone' }).click();
  await expect(page.getByLabel('Ozone values')).toContainText('3 mm');
  await nav.getByRole('button', { name: 'Aerosols' }).click();
  await expect(page.locator('.center-stage')).toContainText('cloud condensation nuclei');
});
