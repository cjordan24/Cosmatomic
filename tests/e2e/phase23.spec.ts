/** Phase 23 browser verification (Meteorology: climate history and Earth systems). Screenshots → screenshots/phase-23/. Offline/deterministic. */
import { test, expect, type Page } from '@playwright/test';
import { mkdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '../../screenshots/phase-23');
mkdirSync(OUT, { recursive: true });
const INDEX = join(OUT, 'captures.json');
const log: Record<string, string> = existsSync(INDEX) ? JSON.parse(readFileSync(INDEX, 'utf8')) : {};
async function shot(page: Page, name: string, description: string) {
  await page.locator('.stage-head h1').first().waitFor({ state: 'visible' });
  await page.waitForTimeout(1200);   // let a 3D view that was just left finish tearing down
  await page.screenshot({ path: join(OUT, `${name}.png`), animations: 'disabled' });
  log[`${name}.png`] = description;
  writeFileSync(INDEX, JSON.stringify(log, null, 2));
  const md = ['# Phase 23 screenshots', '', 'Generated by `tests/e2e/phase23.spec.ts` from the running application (Playwright, Chromium + SwiftShader). Not edited.', '',
    ...Object.entries(log).sort(([a], [b]) => a.localeCompare(b)).map(([f, d]) => `- **${f}** — ${d}`), ''].join('\n');
  writeFileSync(join(OUT, 'INDEX.md'), md);
}
const errors: string[] = [];
test.beforeEach(({ page }) => { page.on('pageerror', (e) => errors.push(e.message)); });
test.afterEach(() => { expect(errors, errors.join(' | ')).toEqual([]); });


const fits = async (page: import('@playwright/test').Page) => {
  const bar = await page.locator('header.topbar').boundingBox(), acts = await page.locator('.topbar-actions').boundingBox();
  expect(acts!.x + acts!.width).toBeLessThanOrEqual(bar!.x + bar!.width + 1);
};

test('136 ice ages: 800,000 years of orbital forcing, CO₂ and Antarctic temperature on one time axis', async ({ page }) => {
  await page.goto('/#/meteorology');
  await page.getByRole('navigation', { name: 'Meteorology sections' }).getByRole('button', { name: 'Climate ▾' }).click();
  await page.getByRole('menuitem', { name: 'Ice ages and the orbit' }).click();
  await expect(page).toHaveURL(/#\/meteorology\/iceages$/);
  await fits(page);
  const v = page.getByLabel('Records at this time');
  await expect(v).toContainText(/1[89]\d(\.\d)? ppm/);
  await expect(page.getByLabel('Correlation')).toContainText(/0\.[89]/);
  await shot(page, '136a-lgm', 'Ice ages (Phase 23): 20,000 years ago — Berger & Loutre (1991) orbital sunshine, Bereiter et al. (2015) CO₂ near 190 ppm and Jouzel et al. (2007) Antarctic temperature about 9 °C below the last millennium; CO₂ and temperature correlate (r ≈ 0.86).');
  await page.getByRole('button', { name: 'Last interglacial' }).click();
  await expect(v).toContainText('+');
  await page.getByRole('radiogroup', { name: 'Orbital record' }).getByRole('radio', { name: 'Obliquity (tilt)' }).click();
  await expect(page.getByRole('img', { name: 'Orbital record' })).toBeVisible();
  await shot(page, '136b-interglacial', 'The last interglacial, about 128,000 years ago: Antarctica warmer than the last millennium, CO₂ near its interglacial peak; obliquity shown above.');
});

test('137 climate through geological time: a log-scale timeline with the time scale, twenty events labelled by evidence, and proxies', async ({ page }) => {
  await page.goto('/#/meteorology');
  await page.getByRole('navigation', { name: 'Meteorology sections' }).getByRole('button', { name: 'Climate ▾' }).click();
  await page.getByRole('menuitem', { name: 'Climate through geological time' }).click();
  await expect(page).toHaveURL(/#\/meteorology\/deeptime$/);
  await fits(page);
  await expect(page.getByLabel('Event title')).toContainText('Paleocene–Eocene');
  await expect(page.getByLabel('What is known')).toContainText('31.6 °C');
  await shot(page, '137a-petm', 'Climate through geological time (Gate 23.2): a log timeline from 4.6 Ga with the USGS eons, eras and periods; the PETM, 56 Ma — 5–8 °C warming (Climate.gov) and a global mean of 31.6 °C (27.2–34.5, Inglis et al. 2020); proxies explained by NOAA.');
  await page.getByLabel('Events').getByRole('button', { name: /End-Permian/ }).click();
  await expect(page.getByLabel('What is known')).toContainText('96% of species');
  await page.getByLabel('Events').getByRole('button', { name: /Great Oxidation/ }).click();
  await expect(page.getByLabel('What is known')).toContainText('not reliably quantified');
  await shot(page, '137b-goe', 'The Great Oxidation Event, about 2.4 billion years ago (NASA Astrobiology) — where no accredited oxygen level exists, the app says so instead of guessing.');
});
