/** Phase 22 browser verification (Meteorology: other worlds). Screenshots → screenshots/phase-22/. Offline/deterministic. */
import { test, expect, type Page } from '@playwright/test';
import { mkdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '../../screenshots/phase-22');
mkdirSync(OUT, { recursive: true });
const INDEX = join(OUT, 'captures.json');
const log: Record<string, string> = existsSync(INDEX) ? JSON.parse(readFileSync(INDEX, 'utf8')) : {};
async function shot(page: Page, name: string, description: string) {
  await page.locator('.stage-head h1').first().waitFor({ state: 'visible' });
  await page.waitForTimeout(1200);   // let a 3D view that was just left finish tearing down
  await page.screenshot({ path: join(OUT, `${name}.png`), animations: 'disabled' });
  log[`${name}.png`] = description;
  writeFileSync(INDEX, JSON.stringify(log, null, 2));
  const md = ['# Phase 22 screenshots', '', 'Generated by `tests/e2e/phase22.spec.ts` from the running application (Playwright, Chromium + SwiftShader). Not edited.', '',
    ...Object.entries(log).sort(([a], [b]) => a.localeCompare(b)).map(([f, d]) => `- **${f}** — ${d}`), ''].join('\n');
  writeFileSync(join(OUT, 'INDEX.md'), md);
}
const errors: string[] = [];
test.beforeEach(({ page }) => { page.on('pageerror', (e) => errors.push(e.message)); });
test.afterEach(() => { expect(errors, errors.join(' | ')).toEqual([]); });


const fits = async (page: import('@playwright/test').Page) => {
  const bar = await page.locator('header.topbar').boundingBox(), acts = await page.locator('.topbar-actions').boundingBox();
  expect(acts!.x + acts!.width).toBeLessThanOrEqual(bar!.x + bar!.width + 1);
};

test('135 other worlds: an atmosphere library, a comparison engine that flags reference levels, greenhouse warming and internal heat', async ({ page }) => {
  await page.goto('/#/meteorology');
  await page.getByRole('navigation', { name: 'Meteorology sections' }).getByRole('button', { name: 'Other worlds' }).click();
  await expect(page).toHaveURL(/#\/meteorology\/planets$/);
  await fits(page);
  const v = page.getByLabel('Atmosphere values');
  await expect(v).toContainText('92 bars'); await expect(v).toContainText('15.8 km');
  await expect(page.getByLabel('Findings')).toContainText('four Earth days');
  await shot(page, '135a-venus', 'Other worlds (Phase 22): Venus from the NSSDCA fact sheet (92 bar, 737 K, scale height 15.9 km — 15.8 km recomputed from its own T, M and g), with tagged findings: NASA’s runaway greenhouse and ESA Venus Express super-rotation.');
  await page.getByRole('radiogroup', { name: 'Worlds' }).getByRole('radio', { name: 'Jupiter' }).click();
  await expect(page.locator('.stage-head')).toContainText('1 bar');
  await expect(page.getByRole('img', { name: 'Great Red Spot width' })).toBeVisible();
  await shot(page, '135b-jupiter', 'Jupiter at the 1-bar level (no solid surface), belts and zones, Juno depths, and the shrinking Great Red Spot from the late 1800s to Juno’s 2017 measurement.');
  const nav = page.getByRole('navigation', { name: 'Planets sections' });
  await nav.getByRole('button', { name: 'Compare' }).click();
  await page.getByRole('group', { name: 'Worlds' }).getByRole('checkbox', { name: 'Jupiter' }).click();
  await expect(page.getByRole('note')).toContainText('no solid surface');
  await shot(page, '135c-compare', 'Comparison engine: Earth, Mars and Jupiter side by side, with a warning that the giant’s values are at 1 bar, not a surface; pressure falling with height for each.');
  await nav.getByRole('button', { name: 'Energy & escape' }).click();
  await expect(page.getByLabel('Greenhouse values')).toContainText('+510');
  await expect(page.getByRole('table', { name: 'Internal heat' })).toContainText('2.62');
});
