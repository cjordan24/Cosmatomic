/** Phase 18 browser verification (Aerospace & Space Systems). Screenshots → screenshots/phase-18/. Offline/deterministic. */
import { test, expect, type Page } from '@playwright/test';
import { mkdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '../../screenshots/phase-18');
mkdirSync(OUT, { recursive: true });
const INDEX = join(OUT, 'captures.json');
const log: Record<string, string> = existsSync(INDEX) ? JSON.parse(readFileSync(INDEX, 'utf8')) : {};
async function shot(page: Page, name: string, description: string) {
  await page.locator('.stage-head h1').first().waitFor({ state: 'visible' });
  await page.waitForTimeout(1200);   // let a 3D view that was just left finish tearing down
  await page.screenshot({ path: join(OUT, `${name}.png`), animations: 'disabled' });
  log[`${name}.png`] = description;
  writeFileSync(INDEX, JSON.stringify(log, null, 2));
  const md = ['# Phase 18 screenshots', '', 'Generated by `tests/e2e/phase18.spec.ts` from the running application (Playwright, Chromium + SwiftShader). Not edited.', '',
    ...Object.entries(log).sort(([a], [b]) => a.localeCompare(b)).map(([f, d]) => `- **${f}** — ${d}`), ''].join('\n');
  writeFileSync(join(OUT, 'INDEX.md'), md);
}
const errors: string[] = [];
test.beforeEach(({ page }) => { page.on('pageerror', (e) => errors.push(e.message)); });
test.afterEach(() => { expect(errors, errors.join(' | ')).toEqual([]); });


test('125 spacecraft and space systems: fleet, rocket equation, orbits, RTG power, the radio link, pointing and heat, the instrument-to-archive chain', async ({ page }) => {
  await page.goto('/#/engineering');
  await page.getByRole('navigation', { name: 'Engineering sections' }).getByRole('button', { name: 'Hardware ▾' }).click();
  await page.getByRole('menuitem', { name: 'Spacecraft & space systems' }).click();
  await expect(page).toHaveURL(/#\/engineering\/space$/);
  const facts = page.getByLabel('Spacecraft facts');
  await expect(facts).toContainText('Sept. 5, 1977'); await expect(facts).toContainText('721.9 kg');
  await expect(page.locator('.center-stage')).toContainText('22.8 hours');
  await shot(page, '125a-voyager', 'Spacecraft (Phase 18): Voyager 1 from NASA’s mission pages — launch, mass, three RTGs of about 158 We each, 164.7 AU on 21 Aug 2024 (22.8 light-hours), and the two pages’ disagreement on how many instruments still work.');
  await page.getByRole('option', { name: /Hubble/ }).click();
  await expect(page.locator('.center-stage')).toContainText('560 kilometers');
  const nav = page.getByRole('navigation', { name: 'Space sections' });
  await nav.getByRole('button', { name: 'Rockets' }).click();
  await expect(page.getByLabel('Rocket values')).toContainText('7.617');
  await expect(page.locator('.center-stage')).toContainText('9.19');
  await shot(page, '125b-rocket', 'The rocket equation (NASA Glenn): Isp 350 s and mass ratio 9.2 give Δu 7.62 km/s; NASA’s worked example prints MR = 10 where its inputs give 9.19.');
  await nav.getByRole('button', { name: 'Orbits' }).click();
  await expect(page.getByLabel('Orbit values')).toContainText('7.669');
  await expect(page.getByLabel('Transfer values')).toContainText('5.6 km/s');
  await shot(page, '125c-orbits', 'Orbits: 7.67 km/s at 400 km (NASA Glenn’s formula, checked against its 17,478 mph); escape speed from Moulton 1914; an Earth→Mars Hohmann transfer of 5.6 km/s and about 259 days, derived from vis-viva.');
  await nav.getByRole('button', { name: 'Power' }).click();
  await expect(page.getByLabel('Voyager power values')).toContainText('330');
  await expect(page.getByLabel('Sunlight values')).toContainText('50.3');
  await shot(page, '125d-power', 'Power far from the Sun: Voyager’s 474 W at launch and NASA’s 225 W in 2023 against Pu-238 decay alone (330 W; half-life 87.7 y, DOE); sunlight at Jupiter 1361/5.2² = 50.3 W/m².');
  await nav.getByRole('button', { name: 'Radio' }).click();
  await expect(page.getByLabel('Yuen example')).toContainText('3.2');
  await shot(page, '125e-link', 'The radio link (Yuen 1982): Voyager at Jupiter — flux 2.38 × 10⁻¹⁹ W/m² checks; the received power computes to 3.20 × 10⁻¹⁶ W against the printed 3.05 × 10⁻¹⁶ W.');
  await nav.getByRole('button', { name: 'Pointing' }).click();
  await expect(page.getByLabel('Plate values')).toContainText('K');
  await nav.getByRole('button', { name: 'Data' }).click();
  await page.getByRole('button', { name: /6\. Deep Space Network/ }).click();
  await expect(page.getByLabel('Chain step')).toContainText('Goldstone');
  await shot(page, '125f-chain', 'From a photon to a paper: eight quoted steps from detector to archive (NASA Basics of Space Flight, Earthdata, USGS) beside an instrument encyclopedia; New Horizons needed over 15 months to send 6.25 GB.');
});
