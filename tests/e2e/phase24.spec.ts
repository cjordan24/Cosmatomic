/** Phase 24 browser verification (Meteorology: human impact and future climate). Screenshots → screenshots/phase-24/. Offline/deterministic. */
import { test, expect, type Page } from '@playwright/test';
import { mkdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '../../screenshots/phase-24');
mkdirSync(OUT, { recursive: true });
const INDEX = join(OUT, 'captures.json');
const log: Record<string, string> = existsSync(INDEX) ? JSON.parse(readFileSync(INDEX, 'utf8')) : {};
async function shot(page: Page, name: string, description: string) {
  await page.locator('.stage-head h1').first().waitFor({ state: 'visible' });
  await page.waitForTimeout(1200);   // let a 3D view that was just left finish tearing down
  await page.screenshot({ path: join(OUT, `${name}.png`), animations: 'disabled' });
  log[`${name}.png`] = description;
  writeFileSync(INDEX, JSON.stringify(log, null, 2));
  const md = ['# Phase 24 screenshots', '', 'Generated by `tests/e2e/phase23.spec.ts` from the running application (Playwright, Chromium + SwiftShader). Not edited.', '',
    ...Object.entries(log).sort(([a], [b]) => a.localeCompare(b)).map(([f, d]) => `- **${f}** — ${d}`), ''].join('\n');
  writeFileSync(join(OUT, 'INDEX.md'), md);
}
const errors: string[] = [];
test.beforeEach(({ page }) => { page.on('pageerror', (e) => errors.push(e.message)); });
test.afterEach(() => { expect(errors, errors.join(' | ')).toEqual([]); });


const fits = async (page: import('@playwright/test').Page) => {
  const bar = await page.locator('header.topbar').boundingBox(), acts = await page.locator('.topbar-actions').boundingBox();
  expect(acts!.x + acts!.width).toBeLessThanOrEqual(bar!.x + bar!.width + 1);
};

test('139 human activities: carbon budget, sectors and methane, life-cycle electricity and cement, waste heat and water, ozone and interventions', async ({ page }) => {
  await page.goto('/#/meteorology');
  await page.getByRole('navigation', { name: 'Meteorology sections' }).getByRole('button', { name: 'Climate ▾' }).click();
  await page.getByRole('menuitem', { name: 'Human activities' }).click();
  await expect(page).toHaveURL(/#\/meteorology\/human$/);
  await fits(page);
  const bv = page.getByLabel('Budget values');
  await expect(bv).toContainText('11.2 GtC/yr');
  await expect(bv).toContainText('+0 GtC/yr');
  await page.getByRole('radiogroup', { name: 'Budget period' }).getByRole('radio', { name: 'Year 2024' }).click();
  await expect(bv).toContainText('−1.6');
  await shot(page, '139a-carbon', 'Human activities (Gate 24.1): the Global Carbon Budget 2025 for 2024 — 11.6 GtC emitted, 7.9 stayed in the air, ocean 3.4, land 1.9, leaving an imbalance (−1.7 printed; −1.6 from the rounded parts); land use split into deforestation, regrowth and other fluxes with model ranges.');
  await page.getByRole('navigation', { name: 'Human activities sections' }).getByRole('button', { name: 'Sectors', exact: true }).click();
  await expect(page.getByRole('listbox', { name: 'Sectors' })).toContainText('Power industry — 29.2 %');
  await page.getByRole('listbox', { name: 'Sectors' }).getByRole('option', { name: /Agriculture/ }).click();
  await expect(page.getByLabel('Sector values')).toContainText('6322.7 Mt');
  await expect(page.getByRole('img', { name: 'Methane annual increase' })).toBeVisible();
  await shot(page, '139b-sectors', 'EDGAR 2026: 54.1 Gt CO₂eq in 2025 by sector (shares derived from the report totals; power “nearly 30%”), agriculture selected; NOAA methane annual increase and Global Methane Budget sources with ranges.');
  await page.getByRole('navigation', { name: 'Human activities sections' }).getByRole('button', { name: 'Electricity', exact: true }).click();
  await expect(page.getByLabel('Mix intensity')).toContainText('g CO₂e/kWh');
  await page.getByLabel('Share of Coal').fill('0');
  await page.getByLabel('Share of Natural gas').fill('0');
  await expect(page.getByLabel('Mix intensity')).toContainText(/mix2\d g CO₂e\/kWh/);
  await expect(page.getByLabel('Cement values')).toContainText('0.7848');
  await shot(page, '139c-electricity', 'NREL (2021) life-cycle medians in g CO₂e/kWh with the phase table; a low-carbon grid mix (illustrative weighted mean); cement process CO₂ from Andrew (2019) eq. 1 with Mr(CO₂)/Mr(CaO) = 0.7848 (0.36 t CO₂ per tonne of cement at the 2018 clinker ratio).');
  await page.getByRole('navigation', { name: 'Human activities sections' }).getByRole('button', { name: 'Heat & water', exact: true }).click();
  await expect(page.getByLabel('Heat values', { exact: true })).toContainText('0.037 W/m²');
  await expect(page.getByLabel('Heat island', { exact: true })).toContainText('1–7 °F');
  await shot(page, '139d-heat', 'Waste heat (595 EJ → 18.9 TW → 0.04 W/m²) against 2.7 W/m² greenhouse forcing (ESD editorial, 2023); EPA heat islands; USGS 2015 water withdrawn vs consumed — thermoelectric 133 vs 4.31 Bgal/d.');
  await page.getByRole('navigation', { name: 'Human activities sections' }).getByRole('button', { name: 'Interventions', exact: true }).click();
  await expect(page.getByLabel('Ozone return dates')).toContainText('during the 2060s');
  await expect(page.getByLabel('Removal values')).toContainText('0.011 MtC/yr');
  await shot(page, '139e-ozone', 'Ozone return dates, WMO 2026 vs 2022 (Arctic date no longer given); carbon removal in 2024 about a million times smaller than fossil emissions; solar radiation modification — mechanism, limits and the modelled ozone delay.');
});

test('140 future climate: projections never shown as outcomes — warming levels, sea-level scenarios, ocean and ice, what is known', async ({ page }) => {
  await page.goto('/#/meteorology');
  await page.getByRole('navigation', { name: 'Meteorology sections' }).getByRole('button', { name: 'Climate ▾' }).click();
  await page.getByRole('menuitem', { name: 'Future climate' }).click();
  await expect(page).toHaveURL(/#\/meteorology\/future$/);
  await fits(page);
  await expect(page.getByRole('note', { name: 'Projection notice' })).toContainText('Projections, not predictions');
  await expect(page.getByLabel('US warming')).toContainText('+4.4 to +5.6 °F');
  await expect(page.getByLabel('Projections at this level')).toContainText('10–30 %');
  await expect(page.getByRole('img', { name: 'Timing of 2 °C' })).toContainText('2033–2054');
  await shot(page, '140a-levels', 'Future climate (Gate 24.2): at 2 °C of global warming — US +4.4 to +5.6 °F (very likely), 10–30 % chance of an ice-free Arctic September by 2100, drought, cyclones and sea level as NCA5 ties them to that level; 2 °C crossed 2033–2054 only in the very high scenario.');
  await page.getByRole('radiogroup', { name: 'Global warming level' }).getByRole('radio', { name: '3 °C' }).click();
  await expect(page.getByLabel('US warming')).toContainText('our extrapolation');
  await page.getByRole('radiogroup', { name: 'Global warming level' }).getByRole('radio', { name: '1.5 °C' }).click();
  await expect(page.getByLabel('US warming')).toContainText('not stated for this level');
  const tabs = page.getByRole('navigation', { name: 'Future climate sections' });
  await tabs.getByRole('button', { name: 'Sea level', exact: true }).click();
  await expect(page.getByLabel('Sea level scenarios').first()).toBeVisible();
  await page.getByRole('radiogroup', { name: 'Region' }).getByRole('radio', { name: 'Contiguous US' }).click();
  await expect(page.getByRole('table', { name: 'Sea level scenarios' })).toContainText('2.2');
  await expect(page.getByRole('table', { name: 'Exceedance probabilities' })).toContainText('49%');
  await shot(page, '140b-sea', 'NOAA’s five sea-level scenarios (Sweet et al. 2022) for the contiguous US — 0.6 to 2.2 m by 2100 relative to 2000 — with NCA5’s chance of exceeding each at each warming level.');
  await tabs.getByRole('button', { name: 'Projections?', exact: true }).click();
  await page.getByRole('listbox', { name: 'Kinds of statement' }).getByRole('option', { name: 'Conditional scenario' }).click();
  await expect(page.getByLabel('Definition')).toContainText('neither predictions nor forecasts');
  await shot(page, '140c-kinds', 'What kind of statement? NCA5 glossary definitions (scenario: “neither predictions nor forecasts”), the five NCA5 scenarios and how projections are built.');
  await tabs.getByRole('button', { name: 'Ocean & ice', exact: true }).click();
  await expect(page.getByLabel('pH values')).toContainText('1.41');
  await tabs.getByRole('button', { name: 'Known & unknown', exact: true }).click();
  await expect(page.getByRole('img', { name: 'Climate sensitivity ranges' })).toContainText('2.5–4.0');
  await expect(page.getByRole('list', { name: 'Tipping elements' })).toContainText('Amazon rainforest dieback');
  await shot(page, '140d-known', 'Well established vs under investigation (NCA5); climate sensitivity — two likely ranges in the same report (2.5–4.0 and 2.6–3.9 °C) — and ten possible tipping elements listed in words.');
});
