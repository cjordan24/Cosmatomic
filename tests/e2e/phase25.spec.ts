/** Phase 25 browser verification (Meteorology: environmental sandbox). Screenshots → screenshots/phase-25/. Offline/deterministic. */
import { test, expect, type Page } from '@playwright/test';
import { mkdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '../../screenshots/phase-25');
mkdirSync(OUT, { recursive: true });
const INDEX = join(OUT, 'captures.json');
const log: Record<string, string> = existsSync(INDEX) ? JSON.parse(readFileSync(INDEX, 'utf8')) : {};
async function shot(page: Page, name: string, description: string) {
  await page.locator('.stage-head h1').first().waitFor({ state: 'visible' });
  await page.waitForTimeout(1200);
  await page.screenshot({ path: join(OUT, `${name}.png`), animations: 'disabled' });
  log[`${name}.png`] = description;
  writeFileSync(INDEX, JSON.stringify(log, null, 2));
  const md = ['# Phase 25 screenshots', '', 'Generated by `tests/e2e/phase25.spec.ts` from the running application (Playwright, Chromium + SwiftShader). Not edited.', '',
    ...Object.entries(log).sort(([a], [b]) => a.localeCompare(b)).map(([f, d]) => `- **${f}** — ${d}`), ''].join('\n');
  writeFileSync(join(OUT, 'INDEX.md'), md);
}
const errors: string[] = [];
test.beforeEach(({ page }) => { page.on('pageerror', (e) => errors.push(e.message)); });
test.afterEach(() => { expect(errors, errors.join(' | ')).toEqual([]); });
const fits = async (page: Page) => {
  const bar = await page.locator('header.topbar').boundingBox(), acts = await page.locator('.topbar-actions').boundingBox();
  expect(acts!.x + acts!.width).toBeLessThanOrEqual(bar!.x + bar!.width + 1);
};

test('141 environmental sandbox: presets from the fact sheets, dependent variables, a gravity override, a region, save and compare', async ({ page }) => {
  await page.goto('/#/meteorology');
  await page.getByRole('navigation', { name: 'Meteorology sections' }).getByRole('button', { name: 'Sandbox' }).click();
  await expect(page).toHaveURL(/#\/meteorology\/sandbox$/);
  await fits(page);
  await expect(page.getByLabel('Gravity', { exact: true })).toContainText('9.8');
  await expect(page.getByLabel('Energy balance')).toContainText('255');
  await page.getByRole('radiogroup', { name: 'Preset' }).getByRole('radio', { name: 'Venus' }).click();
  await expect(page.getByLabel('Energy balance')).toContainText(/Greenhouse warming.*5\d\d K/);
  await shot(page, '141a-venus', 'Environmental sandbox (Phase 25): Venus from the NSSDCA fact sheet — gravity from mass and radius, sunlight 2,601 W/m², emission temperature ≈ 227 K against a measured 737 K: about 510 K of greenhouse warming.');
  await page.getByRole('radiogroup', { name: 'Preset' }).getByRole('radio', { name: 'Earth' }).click();
  await page.getByLabel('Distance from the star').fill(String(Math.log10(1.52)));
  await expect(page.getByLabel('Sunlight')).toContainText(/59\d(\.\d)? W\/m²/);
  await expect(page.getByLabel('Energy balance')).toContainText('— (your world has none)');
  await page.getByLabel('Theoretical gravity override').check();
  await expect(page.getByLabel('Gravity', { exact: true })).toContainText('(override)');
  await shot(page, '141b-earth-at-mars', 'Earth moved to Mars’s distance (1.52 au): sunlight falls to ≈ 590 W/m² and the emission temperature drops; the measured temperature no longer applies; gravity override switched on.');
  await page.getByRole('navigation', { name: 'Sandbox sections' }).getByRole('button', { name: 'Region', exact: true }).click();
  await page.getByLabel('Mountain height').fill('4');
  await expect(page.getByLabel('Rain shadow values')).toContainText('yes');
  await expect(page.getByLabel('Cyclone checklist')).toContainText('✓ Sea surface 28 °C');
  await shot(page, '141c-region', 'The regional lab: a 4 km mountain — the parcel saturates on the windward side and arrives warmer and drier on the lee side; heat index; the tropical-cyclone formation checklist with its sources.');
  page.on('dialog', (d) => d.accept(`exp-${Date.now() % 1000}`));
  await page.getByRole('button', { name: '💾 Save this experiment' }).click();
  await page.getByRole('navigation', { name: 'Sandbox sections' }).getByRole('button', { name: 'Planet', exact: true }).click();
  await page.getByRole('button', { name: '💾 Save this experiment' }).click();
  await page.getByRole('navigation', { name: 'Sandbox sections' }).getByRole('button', { name: 'Saved & compare' }).click();
  await expect(page.getByRole('list', { name: 'Saved experiments' }).getByRole('listitem')).toHaveCount(2);
  await expect(page.getByRole('table', { name: 'Comparison' })).toBeVisible();
  await shot(page, '141d-compare', 'Saved experiments (stored in this browser) compared side by side.');
});
