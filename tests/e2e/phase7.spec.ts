/** Phase 7 browser verification (Cosmology & Observable Universe). Screenshots → screenshots/phase-07/. Offline/deterministic. */
import { test, expect, type Page } from '@playwright/test';
import { mkdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '../../screenshots/phase-07');
mkdirSync(OUT, { recursive: true });
const INDEX = join(OUT, 'captures.json');
const log: Record<string, string> = existsSync(INDEX) ? JSON.parse(readFileSync(INDEX, 'utf8')) : {};
async function shot(page: Page, name: string, description: string) {
  await page.waitForTimeout(700);
  await page.screenshot({ path: join(OUT, `${name}.png`) });
  log[`${name}.png`] = description;
  writeFileSync(INDEX, JSON.stringify(log, null, 2));
  const md = ['# Phase 7 screenshots', '', 'Generated by `tests/e2e/phase7.spec.ts` from the running application (Playwright, Chromium + SwiftShader). Not edited.', '',
    ...Object.entries(log).sort(([a], [b]) => a.localeCompare(b)).map(([f, d]) => `- **${f}** — ${d}`), ''].join('\n');
  writeFileSync(join(OUT, 'INDEX.md'), md);
}
const errors: string[] = [];
test.beforeEach(({ page }) => { page.on('pageerror', (e) => errors.push(e.message)); });
test.afterEach(() => { expect(errors, errors.join(' | ')).toEqual([]); });

// ---------------- Gate 7.1 ----------------
test('64 expansion and distances: ΛCDM distances, expansion history, cosmological lensing', async ({ page }) => {
  await page.goto('/#/cosmic');
  await page.getByRole('navigation', { name: 'Cosmic sections' }).getByRole('button', { name: /^Universe/ }).click();
  await page.getByRole('menu', { name: 'Universe' }).getByRole('menuitem', { name: 'Expansion' }).click();
  await expect(page).toHaveURL(/#\/cosmic\/universe$/);
  const info = page.locator('.right-panel');
  await expect(page.getByRole('img', { name: 'Distance measures against redshift' })).toBeVisible();
  await expect(info.getByLabel('Times at the selected redshift')).toContainText('Age today13.786 Gyr'); // Planck 2018 model
  await expect(info).toContainText('13.787 ± 0.02 Gyr');
  await page.getByRole('button', { name: 'z∗ (CMB)' }).click();
  await expect(page).toHaveURL(/z=1089.8/);
  await expect(info).toContainText('kyr'); // age at last scattering
  await page.getByRole('button', { name: 'z = 1', exact: true }).click();
  await expect(info.getByLabel('Distances at the selected redshift')).toContainText('Gpc');
  await shot(page, '64a-universe-distances', 'Expansion & distances (#/cosmic/universe) with Planck 2018 ΛCDM: comoving, luminosity, light-travel and angular-diameter distances against redshift to the CMB (z∗ = 1089.8); values at z = 1, the model age 13.79 Gyr against Planck’s 13.787 ± 0.020 Gyr, and D_M(z∗) against r∗/θ∗.');
  await page.getByRole('radio', { name: 'Einstein–de Sitter (matter only)' }).check();
  await expect(page).toHaveURL(/m=eds/);
  await expect(info.getByLabel('Times at the selected redshift')).toContainText('9.63'); // 2/(3H₀) for H₀ = 67.66
  await page.getByRole('button', { name: 'Expansion history' }).click();
  await expect(page.getByRole('img', { name: 'Scale factor against cosmic time' })).toBeVisible();
  await page.getByRole('radio', { name: 'Planck 2018 ΛCDM' }).check();
  await expect(page.getByLabel('Model landmarks')).toContainText('z = 0.642');
  await expect(page.getByLabel('Cosmic epochs')).toContainText('1089.8 ± 0.21');
  await expect(page.getByLabel('Planck 2018 parameters')).toContainText('67.66 ± 0.42');
  await shot(page, '64b-universe-history', 'Expansion history: the scale factor a(t), the matter, radiation and dark-energy fractions against 1 + z with Planck’s z_re, z∗ and z_eq, and the expansion speed ȧ, whose minimum marks the onset of acceleration (q = 0 at z ≈ 0.64). Planck 2018 epochs with model ages.');
  await page.getByRole('button', { name: 'Cosmological lensing' }).click();
  await expect(page.getByRole('img', { name: 'Angular-diameter distances for lensing' })).toBeVisible();
  await expect(page.getByLabel('Einstein radius')).toContainText('0.63');
  await expect(page.getByLabel('Lensing distances')).toContainText('D_s − D_d');
  await shot(page, '64c-universe-lensing', 'Cosmological lensing distances: D_A(z) from the observer and from a lens at z = 0.5 (Hogg eq. 19) against the incorrect difference D_A(z) − D_A(z_l); a 10¹¹ M☉ point lens with a source at z = 2 gives θ_E ≈ 0.63″.');
  await page.getByRole('button', { name: /Lens plane for 10¹¹/ }).click();
  await expect(page).toHaveURL(/#\/cosmic\/lensing\?lens=cosmo/);
  await expect(page.locator('.right-panel')).toContainText('10¹¹ M☉ galaxy at z = 0.5');
});

