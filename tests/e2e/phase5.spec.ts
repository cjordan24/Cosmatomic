/** Phase 5 browser verification (Interstellar & Stellar). Screenshots → screenshots/phase-05/. Offline/deterministic. */
import { test, expect, type Page } from '@playwright/test';
import { mkdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '../../screenshots/phase-05');
mkdirSync(OUT, { recursive: true });
const INDEX = join(OUT, 'captures.json');
const log: Record<string, string> = existsSync(INDEX) ? JSON.parse(readFileSync(INDEX, 'utf8')) : {};
async function shot(page: Page, name: string, description: string) {
  await page.waitForTimeout(700);
  await page.screenshot({ path: join(OUT, `${name}.png`) });
  log[`${name}.png`] = description;
  writeFileSync(INDEX, JSON.stringify(log, null, 2));
  const md = ['# Phase 5 screenshots', '', 'Generated by `tests/e2e/phase5.spec.ts` from the running application (Playwright, Chromium + SwiftShader). Not edited.', '',
    ...Object.entries(log).sort(([a], [b]) => a.localeCompare(b)).map(([f, d]) => `- **${f}** — ${d}`), ''].join('\n');
  writeFileSync(join(OUT, 'INDEX.md'), md);
}
const errors: string[] = [];
test.beforeEach(({ page }) => { page.on('pageerror', (e) => errors.push(e.message)); });
test.afterEach(() => { expect(errors, errors.join(' | ')).toEqual([]); });

// ---------------- Gate 5.1 ----------------
test('54 nearby-star map: 10 pc catalogue, selection, derived astrometry and references', async ({ page }) => {
  await page.goto('/#/cosmic/stars');
  await expect(page.locator('.left-panel')).toContainText('Within 10 pc');
  await expect(page.getByRole('listbox', { name: 'Nearby systems' }).getByRole('option').first()).toContainText('alf Cen');
  await expect(page.locator('canvas')).toBeVisible();
  await shot(page, '54a-star-map-overview', 'Nearby-star map (#/cosmic/stars): every star, brown dwarf and white dwarf within 10 pc (Reylé et al. 2021, 2023 update) in the galactic frame, Sun at the centre, rings every 2.5 pc, drop lines to the Galactic plane, systems listed by distance.');
  await page.getByLabel('Filter systems').fill('Proxima');
  await expect(page.getByRole('listbox', { name: 'Nearby systems' }).getByRole('option')).toHaveCount(1);
  await page.getByRole('listbox', { name: 'Nearby systems' }).getByRole('option').first().click();
  await expect(page.locator('.right-panel h2')).toHaveText('alf Cen A'); // brightest member opens first
  await page.getByRole('listbox', { name: 'System members' }).getByRole('option', { name: 'Proxima Cen M5.5' }).click();
  const info = page.locator('.right-panel');
  await expect(info.locator('h2')).toHaveText('Proxima Cen');
  await expect(info.getByLabel('Astrometry', { exact: true })).toContainText('768.0665 ± 0.0499');
  await expect(info.getByLabel('Derived astrometry')).toContainText('1.302');
  await expect(info.getByLabel('Spectral type', { exact: true })).toContainText('M5.5');
  await expect(info.getByRole('link', { name: '2020yCat.1350....0G' }).first()).toHaveAttribute('href', /ui\.adsabs\.harvard\.edu\/abs\/2020yCat\.1350\.\.\.\.0G/);
  await expect(info.getByLabel('Spectral-type calibration')).toContainText('2,930 K');
  await expect(page).toHaveURL(/sel=1/);
  await shot(page, '54b-proxima-selected', 'Proxima Centauri selected: catalogue parallax, position, proper motion and radial velocity, each with a NASA ADS link to its original reference; derived distance (1.302 pc / 4.25 ly), galactic l/b and tangential velocity; the M5.5 dwarf calibration (Pecaut & Mamajek) labelled as a typical value, not a measurement.');
  // α Cen A: too bright for Gaia, measured G unknown, estimate not used
  await page.goto('/#/cosmic/stars?sel=3');
  await expect(info.locator('h2')).toHaveText('alf Cen A');
  await expect(info).toContainText('estimated');
  await expect(info.getByLabel('Photometry', { exact: true })).toContainText('unknown');
  // frame switch + CNS5 layer held in the URL
  await page.getByLabel('Reference frame').selectOption('icrs');
  await expect(page).toHaveURL(/frame=icrs/);
  await page.getByLabel('Show CNS5 stars to 20 pc').check();
  await expect(page).toHaveURL(/bg=1/);
  await expect(page.locator('.star-legend')).toContainText('celestial equator');
  await shot(page, '54c-icrs-cns5-20pc', 'Equatorial (ICRS) frame with the CNS5 layer: stars between 10 and 20 pc (Golovin et al. 2023) as dim points, rings every 5 pc; α Cen A selected: too bright for Gaia, so measured G is unknown and the catalogue’s estimate is shown as an estimate only.');
  // scale navigator now routes to the stellar level
  await page.getByTitle('Universal scale navigator').click();
  await expect(page.locator('.scale-nav li.current')).toContainText('Stellar neighbourhood');
});

