/** Phase 8 browser verification (Unified Scale & Relationships). Screenshots → screenshots/phase-08/. Offline/deterministic. */
import { test, expect, type Page } from '@playwright/test';
import { mkdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '../../screenshots/phase-08');
mkdirSync(OUT, { recursive: true });
const INDEX = join(OUT, 'captures.json');
const log: Record<string, string> = existsSync(INDEX) ? JSON.parse(readFileSync(INDEX, 'utf8')) : {};
async function shot(page: Page, name: string, description: string) {
  await page.waitForTimeout(700);
  await page.screenshot({ path: join(OUT, `${name}.png`) });
  log[`${name}.png`] = description;
  writeFileSync(INDEX, JSON.stringify(log, null, 2));
  const md = ['# Phase 8 screenshots', '', 'Generated by `tests/e2e/phase8.spec.ts` from the running application (Playwright, Chromium + SwiftShader). Not edited.', '',
    ...Object.entries(log).sort(([a], [b]) => a.localeCompare(b)).map(([f, d]) => `- **${f}** — ${d}`), ''].join('\n');
  writeFileSync(join(OUT, 'INDEX.md'), md);
}
const errors: string[] = [];
test.beforeEach(({ page }) => { page.on('pageerror', (e) => errors.push(e.message)); });
test.afterEach(() => { expect(errors, errors.join(' | ')).toEqual([]); });

// ---------------- Gate 8.1 ----------------
test('72 scale explorer: sourced reference objects drawn to one linear scale from the proton to the observable universe', async ({ page }) => {
  await page.goto('/#/atomic');
  await page.getByRole('button', { name: 'Scale', exact: true }).click();
  await page.getByRole('button', { name: 'Open the scale explorer →' }).click();
  await expect(page).toHaveURL(/#\/scale$/);
  await expect(page.getByRole('heading', { name: 'Scale of the universe' })).toBeVisible();
  // default window: 10^-9.3 m, molecules and atoms
  const near = page.getByRole('list', { name: 'Reference objects near this window' });
  await expect(near).toContainText('Water molecule');
  await expect(near).toContainText('Buckminsterfullerene');
  await shot(page, '72a-scale-molecules', 'Scale explorer at 501 pm: Bohr radius, atoms (van der Waals), water, glucose, C₆₀ and the NaCl cell drawn to one scale.');

  // choose the Sun from the full list: value, provenance, source, zoom-to-fit
  await page.getByRole('combobox', { name: 'All reference objects' }).selectOption('sun');
  await expect(page).toHaveURL(/sel=sun/);
  const obj = page.getByRole('region', { name: 'Sun' });
  await expect(obj.getByRole('definition').first()).toContainText('1,391,400 km');
  await expect(obj).toContainText('Observed');
  await expect(obj).toContainText('Prša');
  await expect(near).toContainText('Jupiter');
  await shot(page, '72b-scale-sun', 'The Sun (IAU 2015 nominal radius) beside Jupiter, Earth, Sirius B and the Earth–Moon distance.');

  // zoom out ten times with the button, then jump by the ruler to the far end
  const z0 = Number(new URL(page.url().replace('#/', '')).searchParams.get('z'));
  await page.getByRole('button', { name: 'Zoom out ten times' }).click();
  await expect.poll(() => Number(new URL(page.url().replace('#/', '')).searchParams.get('z'))).toBeCloseTo(z0 + 1, 2);

  // the cosmic end: the observable universe is a model quantity (Simulated), with Planck and Hogg as sources
  await page.getByRole('combobox', { name: 'All reference objects' }).selectOption('observable');
  const o = page.getByRole('region', { name: 'Observable universe' });
  await expect(o).toContainText('Simulated');
  await expect(o.getByRole('definition').first()).toContainText('Gpc');
  await shot(page, '72c-scale-observable', 'The comoving radius of the observable universe in Planck 2018 ΛCDM (a model quantity) beside the Hubble distance.');

  // the proton: CODATA 2022
  await page.goto('/#/scale?sel=proton&z=-14.4');
  await expect(page.getByRole('region', { name: 'Proton' })).toContainText('Mohr (2025)');
  await expect(page.getByRole('region', { name: 'Proton' })).toContainText('1.6815 fm');

  // the Galaxy clusters level is now interactive and opens the Coma cluster
  await page.getByRole('combobox', { name: 'Jump to a scale level' }).selectOption('cluster');
  await expect(near).toContainText('Coma cluster');
  await page.getByRole('button', { name: /open the galaxy clusters view/ }).click();
  await expect(page).toHaveURL(/#\/cosmic\/darkmatter\?tab=clusters/);
});
