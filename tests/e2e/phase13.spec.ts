/** Phase 13 browser verification (Waves, Life & Imaging). Screenshots → screenshots/phase-13/. Offline/deterministic. */
import { test, expect, type Page } from '@playwright/test';
import { mkdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '../../screenshots/phase-13');
mkdirSync(OUT, { recursive: true });
const INDEX = join(OUT, 'captures.json');
const log: Record<string, string> = existsSync(INDEX) ? JSON.parse(readFileSync(INDEX, 'utf8')) : {};
async function shot(page: Page, name: string, description: string) {
  await page.waitForTimeout(700);
  await page.screenshot({ path: join(OUT, `${name}.png`) });
  log[`${name}.png`] = description;
  writeFileSync(INDEX, JSON.stringify(log, null, 2));
  const md = ['# Phase 13 screenshots', '', 'Generated by `tests/e2e/phase13.spec.ts` from the running application (Playwright, Chromium + SwiftShader). Not edited.', '',
    ...Object.entries(log).sort(([a], [b]) => a.localeCompare(b)).map(([f, d]) => `- **${f}** — ${d}`), ''].join('\n');
  writeFileSync(join(OUT, 'INDEX.md'), md);
}
const errors: string[] = [];
test.beforeEach(({ page }) => { page.on('pageerror', (e) => errors.push(e.message)); });
test.afterEach(() => { expect(errors, errors.join(' | ')).toEqual([]); });

// ---------------- Gates 13.1–13.3 ----------------
test('107 senses and signals: Helmholtz’s reduced eye and diffraction circle, cone peaks, Fletcher & Munson’s level, Einthoven’s leads', async ({ page }) => {
  await page.goto('/#/biologic');
  await page.getByRole('navigation', { name: 'Biologic sections' }).getByRole('button', { name: 'Waves & life ▾' }).click();
  await page.getByRole('menuitem', { name: 'Senses & signals' }).click();
  await expect(page).toHaveURL(/#\/biologic\/senses$/);
  const bar = await page.locator('header.topbar').boundingBox(), acts = await page.locator('.topbar-actions').boundingBox();
  expect(acts!.x + acts!.width).toBeLessThanOrEqual(bar!.x + bar!.width + 1);
  const eye = page.getByLabel('Eye values');
  await expect(eye).toContainText('6.1');      // δ = 2.440 × 0.0005 × 20 / 4 mm = 6.1 µm
  await expect(eye).toContainText('58.5');     // (4/3 − 1)/5.7 mm
  await expect(page.locator('.stage-head')).toContainText('index of refraction of 4/3 would have a radius of curvature of 5.7 mm');
  await expect(page.getByLabel('Listing values')).toContainText('5.1248');
  await shot(page, '107a-eye', 'The eye as an optical instrument (Gate 13.1): NEI’s path of light; Gullstrand’s reduced eye (n = 4/3, r = 5.7 mm, Helmholtz p. 355) gives the retinal image of a person 10 m away; Helmholtz’s diffraction circle δ = 2.440 lr/d against pupil diameter (p. 196); Listing’s printed radius 5.1248 mm beside f₂ − f₁ = 5.0674 mm.');
  await page.getByRole('button', { name: 'Helmholtz\'s smallest pupil (2 mm)' }).click();
  await expect(eye).toContainText('12.2');     // Helmholtz: 0.0122 mm
  await page.getByRole('navigation', { name: 'Senses sections' }).getByRole('button', { name: 'Colour' }).click();
  const pk = page.getByLabel('Peak wavelengths');
  for (const v of ['566', '541', '441', '555', '506']) await expect(pk).toContainText(v);
  await shot(page, '107b-colour', 'Colour (Gate 13.1): peaks of the Stockman & Sharpe (2000) cone fundamentals (L 566, M 541, S 441 nm) and of the CIE day (555 nm) and night (506 nm) luminosity functions, located in CVRL’s tables; only the peaks are drawn.');
  await page.getByRole('navigation', { name: 'Senses sections' }).getByRole('button', { name: 'Hearing' }).click();
  await expect(page.getByLabel('Sound values')).toContainText('1.00 × 10⁻⁴');   // 60 dB → 10⁻⁴ µW/cm²
  await expect(page.locator('.center-stage')).toContainText('at or above 85 dBA can cause hearing loss');
  await shot(page, '107c-hearing', 'Hearing (Gate 13.2): NIDCD’s path of sound; Fletcher & Munson’s intensity level β = 10 log J + 100 (J in µW/cm², reference 10⁻¹⁶ W/cm²); NIDCD’s 70 and 85 dBA statements.');
  await page.getByRole('navigation', { name: 'Senses sections' }).getByRole('button', { name: 'Heart signals' }).click();
  await page.getByRole('button', { name: 'Einthoven\'s α = 76°' }).click();
  const L = page.getByLabel('Lead values');
  await expect(L).toContainText('0.242'); await expect(L).toContainText('0.961'); await expect(L).toContainText('0.719');
  await expect(page.locator('.stage-head')).toContainText('Each beat of the heart is seen to be accompanied by an electrical variation.');
  await shot(page, '107d-ecg', 'Heart signals (Gate 13.3): Waller (1887) and Einthoven (1912); a heart vector at Einthoven’s α = 76° projected onto leads I, II and III of his equilateral triangle, with lead II − lead I = lead III.');
});

