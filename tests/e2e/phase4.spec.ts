/** Phase 4 browser verification (Matter, Materials, Energy & Wave foundations). Screenshots → screenshots/phase-04/. Offline/deterministic. */
import { test, expect, type Page } from '@playwright/test';
import { mkdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '../../screenshots/phase-04');
mkdirSync(OUT, { recursive: true });
const INDEX = join(OUT, 'captures.json');
const log: Record<string, string> = existsSync(INDEX) ? JSON.parse(readFileSync(INDEX, 'utf8')) : {};
async function shot(page: Page, name: string, description: string) {
  await page.waitForTimeout(500);
  await page.screenshot({ path: join(OUT, `${name}.png`) });
  log[`${name}.png`] = description;
  writeFileSync(INDEX, JSON.stringify(log, null, 2));
  const md = ['# Phase 4 screenshots', '', 'Generated by `tests/e2e/phase4.spec.ts` from the running application (Playwright, Chromium + SwiftShader). Not edited.', '',
    ...Object.entries(log).sort(([a], [b]) => a.localeCompare(b)).map(([f, d]) => `- **${f}** — ${d}`), ''].join('\n');
  writeFileSync(join(OUT, 'INDEX.md'), md);
}
const errors: string[] = [];
test.beforeEach(({ page }) => { page.on('pageerror', (e) => errors.push(e.message)); });
test.afterEach(() => { expect(errors, errors.join(' | ')).toEqual([]); });

// ---------------- Gate 4.1 ----------------
test('41 reaction library: curated equation with conservation table and molecule links', async ({ page }) => {
  await page.goto('/#/atomic/reactions/photosynthesis-net');
  await expect(page.locator('.center-stage h1')).toHaveText('Oxygenic photosynthesis (net equation)');
  await expect(page.getByLabel('Atom balance').first()).toContainText('✓');
  await expect(page.locator('.right-panel')).toContainText('planned');
  await shot(page, '41-reaction-library', 'Reaction library: net photosynthesis equation with species cards linked to the 3D molecule viewer, machine-checked atom/charge balance, net-equation caveats and registry connections (Biologic processes shown as planned, not as working links).');
  await page.locator('.species-card', { hasText: 'glucose' }).getByRole('button', { name: /3D structure/ }).click();
  await expect(page).toHaveURL(/molecules\/pubchem-5793/);
  await expect(page.locator('.right-panel')).toContainText('Reactions · curated library');
});

test('42 equation validation: balancing, charge conservation and explicit unsupported state', async ({ page }) => {
  await page.goto('/#/atomic/reactions/permanganate-iron');
  const input = page.getByLabel('Chemical equation input');
  await input.fill('C3H8 + O2 -> CO2 + H2O');
  await page.getByRole('button', { name: 'Check' }).click();
  const status = page.getByRole('status', { name: 'Equation analysis' });
  await expect(status).toContainText('curated reaction');
  await expect(status).toContainText('5 O₂');
  await input.fill('N2 + O2 -> NO2');
  await page.getByRole('button', { name: 'Check' }).click();
  await expect(status).toContainText('balanced · not verified');
  await shot(page, '42-equation-validation', 'User equation “N₂ + O₂ → NO₂” balanced exactly (rational null space) to N₂ + 2 O₂ → 2 NO₂ but flagged “not verified” because it is not in the curated library; background: permanganate/iron(II) redox with charge (+17 = +17) conserved.');
  await input.fill('Xe + F2');
  await page.getByRole('button', { name: 'Check' }).click();
  await expect(status).toContainText('unsupported');
  await expect(status).toContainText('Product prediction is not supported');
});

test('40 source index: every source with link, institution and author note', async ({ page }) => {
  await page.goto('/#/atomic/reactions/chapman-o3-photolysis');
  await page.locator('.right-panel').getByRole('button', { name: /Chapman \(1930\)/ }).click();
  await expect(page).toHaveURL(/#\/sources\/chapman-1930/);
  const entry = page.getByRole('listitem', { name: 'A theory of upper-atmospheric ozone' });
  await expect(entry).toContainText('About the authors');
  await expect(entry).toContainText('Sydney Chapman');
  await shot(page, '40-source-index', 'Source index (#/sources): every citation behind the app — peer-reviewed articles, academic texts, national laboratories and standards bodies — with DOI/official link, institution, licence, a verified author note and what it is used for. Reached here from a reaction’s source link.');
});
