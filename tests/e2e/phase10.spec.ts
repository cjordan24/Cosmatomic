/** Phase 10 browser verification (Optics, Radiation & Energy). Screenshots → screenshots/phase-10/. Offline/deterministic. */
import { test, expect, type Page } from '@playwright/test';
import { mkdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '../../screenshots/phase-10');
mkdirSync(OUT, { recursive: true });
const INDEX = join(OUT, 'captures.json');
const log: Record<string, string> = existsSync(INDEX) ? JSON.parse(readFileSync(INDEX, 'utf8')) : {};
async function shot(page: Page, name: string, description: string) {
  await page.waitForTimeout(700);
  await page.screenshot({ path: join(OUT, `${name}.png`) });
  log[`${name}.png`] = description;
  writeFileSync(INDEX, JSON.stringify(log, null, 2));
  const md = ['# Phase 10 screenshots', '', 'Generated by `tests/e2e/phase10.spec.ts` from the running application (Playwright, Chromium + SwiftShader). Not edited.', '',
    ...Object.entries(log).sort(([a], [b]) => a.localeCompare(b)).map(([f, d]) => `- **${f}** — ${d}`), ''].join('\n');
  writeFileSync(join(OUT, 'INDEX.md'), md);
}
const errors: string[] = [];
test.beforeEach(({ page }) => { page.on('pageerror', (e) => errors.push(e.message)); });
test.afterEach(() => { expect(errors, errors.join(' | ')).toEqual([]); });

// ---------------- Gate 10.1 ----------------
test('86 geometric optics: refraction and total reflection, lens and mirror traces against Drude, prism dispersion against Southall', async ({ page }) => {
  await page.goto('/#/spectral');
  await page.getByRole('navigation', { name: 'Spectral sections' }).getByRole('button', { name: 'Light ▾' }).click();
  await page.getByRole('menuitem', { name: 'Geometric optics' }).click();
  await expect(page).toHaveURL(/#\/spectral\/optics$/);
  await expect(page.getByRole('heading', { name: /Reflection and refraction/ })).toBeVisible();
  const refr = page.getByLabel('Refraction result');
  await expect(refr).toContainText(/48\.589 °/);           // critical angle water → air at 589 nm
  await expect(refr).toContainText(/58\.989 °/);          // refraction at 40°
  await shot(page, '86a-refraction', 'Water → air at 589 nm: reflection, refraction at 40° (n_a sin φ_a = n_b sin φ_b) and the 48.6° critical angle (Drude §1), with water’s index from its dispersion formula.');
  await page.getByRole('button', { name: 'Water → air beyond the critical angle' }).click();
  await expect(refr).toContainText('none (total reflection)');
  await page.getByRole('navigation', { name: 'Geometric optics sections' }).getByRole('button', { name: 'Lens' }).click();
  const lens = page.getByLabel('Lens result');
  await expect(lens).toContainText(/54\.5\d/);             // fused silica, r₁ = 50, r₂ = −50: 1/f = (n − 1)(2/50)
  await expect(page.getByRole('table', { name: 'Chromatic aberration' })).toContainText('450');
  await shot(page, '86b-lens', 'Exact ray trace through a 4 mm thick fused-silica biconvex lens (r = ±50 mm): marginal rays focus short of the paraxial focus; the thin-lens focal length 54.5 mm from Drude eq. 22 and the chromatic shift of the traced focal length.');
  await page.getByRole('navigation', { name: 'Geometric optics sections' }).getByRole('button', { name: 'Mirror' }).click();
  await expect(page.getByLabel('Mirror result')).toContainText('100');
  await page.getByRole('navigation', { name: 'Geometric optics sections' }).getByRole('button', { name: 'Prism' }).click();
  await page.getByRole('button', { name: 'Set minimum deviation at 589 nm' }).click();
  await expect(page.getByLabel('Prism result')).toContainText(/33\.6\d/);
  await expect(page.getByRole('table', { name: 'Prism deviation' })).toContainText('700');
  await shot(page, '86c-prism', 'A 60° fused-silica prism at minimum deviation for 589 nm (33.6°, Southall eq. 27): seven wavelengths from 400 to 700 nm traced through both faces, blue deviated most.');
});

